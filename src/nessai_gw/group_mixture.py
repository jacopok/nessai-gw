#: Parameters the group acts on, in the order expected by the flow.  These
#: are the *measure-preserving* coordinates: ``sin_dec = sin(dec)`` and
#: ``cos_theta_jn = cos(theta_jn)`` rather than the raw angles, so the action
#: has unit Jacobian (see the module docstring).
TRIANGULAR_DETECTOR_PARAMETERS = [
    "ra",
    "sin_dec",
    "cos_theta_jn",
    "psi",
    "phase",
    "geocent_time",
]

#: Number of group elements of the long-wavelength-exact group (``Z4 x Z2``).
TRIANGULAR_DETECTOR_GROUP_SIZE = 8

#: Number of group elements with the extra (approximate) ``phase -> phase + pi``
#: (2, 2)-mode reflection folded in (``Z4 x Z2 x Z2``); see
#: :class:`TriangularDetectorGroupAction` ``phase_reflection``.
TRIANGULAR_DETECTOR_GROUP_SIZE_PHASE = 16

_TWO_PI = 2.0 * np.pi

#: Small offset guarding divisions by a vector norm in the prime-space adapter.
_EPS = 1e-30

#: nessai ``Angle`` reparameterisation convention: the Cartesian angle stored by
#: the flow is ``physical_angle * scale``.  ``angle-pi`` (used for ``psi``) has
#: ``scale = 2``.  ``psi`` is the only extrinsic coordinate still carried as an
#: ``Angle`` Cartesian pair.
_ANGLE_SCALE = {"psi": 2.0}

#: ``polarisation-phase`` scale (must match the value the ``polarisation-phase``
#: reparameterisation is registered with).  The flow coordinate is
#: ``delta_phase_prime = (((phase + sign(cos theta_jn) * psi) * scale) mod 2*pi)
#: / pi - 1`` in ``[-1, 1)``; ``scale = 1`` -> period ``2*pi`` (bijective).
_DELTA_PHASE_SCALE = 1.0

#: ``geocent_time`` prime coordinate is ``(geocent_time - reference_time) /
#: _GEOCENT_SCALE``.  A fixed scale (rather than data-driven bounds) keeps the
#: group's additive light-travel-delay shift exact under a constant offset.
#: Tuned for an ET-scale site; a very different geometry may want it revisited.
_GEOCENT_SCALE = 5e-3

#: Numerical-safety floor on the measured canonical std (nessai's
#: ``DiscreteGroupMixtureFlowWrapper`` clamps to this, purely to avoid a
#: literal std of 0); it should stay far below any real posterior width.
_MIN_CANON_STD = 1e-6


def detector_plane_normal(interferometers) -> np.ndarray:
    """Unit normal to the plane of a triangular interferometer.

    Parameters
    ----------
    interferometers : iterable
        Iterable of bilby / bilby_xG ``Interferometer`` objects (the three
        nested detectors of the triangle), each exposing ``geometry.x`` and
        ``geometry.y`` unit arm vectors in the Earth-fixed frame.

    Returns
    -------
    numpy.ndarray
        The mean arm-plane normal, normalised to unit length.
    """
    normals = []
    for ifo in interferometers:
        x = np.asarray(ifo.geometry.x, dtype=float)
        y = np.asarray(ifo.geometry.y, dtype=float)
        n = np.cross(x, y)
        normals.append(n / np.linalg.norm(n))
    n = np.mean(normals, axis=0)
    return n / np.linalg.norm(n)


def detector_vertex(interferometers) -> np.ndarray:
    """Mean geocentric vertex position (metres) of a triangular interferometer.

    Parameters
    ----------
    interferometers : iterable
        Iterable of bilby / bilby_xG ``Interferometer`` objects, each exposing
        ``geometry.vertex`` (its Earth-fixed position in metres).

    Returns
    -------
    numpy.ndarray
        The mean of the three vertex positions.
    """
    vertices = [
        np.asarray(ifo.geometry.vertex, dtype=float) for ifo in interferometers
    ]
    return np.mean(vertices, axis=0)


def detector_vertex_from_geodetic(
    latitude: float, longitude: float, height: float = 0.0
) -> np.ndarray:
    """Earth-fixed position (metres) from WGS84 geodetic coordinates.

    Parameters
    ----------
    latitude, longitude : float
        Geodetic latitude and longitude in radians.
    height : float, optional
        Height above the WGS84 ellipsoid in metres (default 0).
    """
    a = 6378137.0
    f = 1.0 / 298.257223563
    e2 = f * (2.0 - f)
    sin_lat = np.sin(latitude)
    n = a / np.sqrt(1.0 - e2 * sin_lat**2)
    return np.array(
        [
            (n + height) * np.cos(latitude) * np.cos(longitude),
            (n + height) * np.cos(latitude) * np.sin(longitude),
            (n * (1.0 - e2) + height) * sin_lat,
        ]
    )


def _detector_frame_basis(
    plane_normal: np.ndarray, azimuth_offset: float = 0.0
) -> np.ndarray:
    """Orthonormal Earth-fixed basis ``[e1, e2, e3]`` with ``e3`` the normal.

    ``e1`` is the (Earth-fixed) z-axis projected into the plane, then rotated
    about ``e3`` by ``azimuth_offset``.  The physical group action is
    equivariant under this in-plane rotation (it only shifts ``lambda`` and
    ``psi`` by a constant), but the *fundamental domain* -- detector-frame
    azimuth in ``[0, pi/2)`` -- is not: ``azimuth_offset`` moves the Z4 seams
    by a fixed amount.  Prefer the data-driven, per-expert seams of
    :class:`AdaptiveFundamentalDomain`; a non-zero offset is kept for
    reproducing older runs.
    """
    e3 = np.asarray(plane_normal, dtype=float)
    e3 = e3 / np.linalg.norm(e3)
    e1 = np.array([0.0, 0.0, 1.0]) - e3[2] * e3
    e1 = e1 / np.linalg.norm(e1)
    e2 = np.cross(e3, e1)
    if azimuth_offset:
        c, s = np.cos(azimuth_offset), np.sin(azimuth_offset)
        e1, e2 = c * e1 + s * e2, -s * e1 + c * e2
    return np.stack([e1, e2, e3])


def _uvw(phi: torch.Tensor, theta: torch.Tensor):
    """bilby (Nishizawa 2009) frame vectors for colatitude/azimuth angles."""
    cp, sp = torch.cos(phi), torch.sin(phi)
    ct, st = torch.cos(theta), torch.sin(theta)
    zero = torch.zeros_like(phi)
    u = torch.stack([cp * ct, ct * sp, -st], dim=-1)
    v = torch.stack([-sp, cp, zero], dim=-1)
    w = torch.stack([st * cp, st * sp, ct], dim=-1)
    return u, v, w


def _polarisation_angle(m: torch.Tensor, u: torch.Tensor, v: torch.Tensor):
    """Recover ``psi`` from ``m``, where ``m = -u sin psi - v cos psi``."""
    return torch.atan2(-(m * u).sum(-1), -(m * v).sum(-1))


class TriangularDetectorGroupAction:
    """Callable eight-element group action for a triangular detector.

    Detector-agnostic: the only inputs that depend on the instrument are the
    Earth-fixed plane normal and vertex position.  :class:`ETTriangleGroupAction`
    is a thin subclass that fills those in with the ET-EMR geometry.

    Instances are the ``group_action_fn`` /  ``in_fundamental_domain`` pair
    consumed by :func:`nessai.flowmodel.group_mixture.make_group_mixture_flow`.

    Parameters
    ----------
    reference_time : float
        Geocentric GPS time of the event.  Only the Greenwich mean sidereal
        time it implies is used (to rotate between the equatorial and
        Earth-fixed frames); the ~tens-of-ms spread of a posterior is
        negligible here.
    plane_normal : array_like
        Unit normal to the detector plane in the Earth-fixed frame.  Use
        :func:`detector_plane_normal` to build one from a bilby interferometer
        list.
    vertex : array_like
        Geocentric position of the detector (metres, Earth-fixed frame), used
        to carry ``geocent_time`` along with the sky transformation.  Use
        :func:`detector_vertex` to build one from a bilby interferometer list.
    phase_reflection : bool, optional
        If ``True``, fold in the extra ``phase -> phase + pi`` (2, 2)-mode
        degeneracy as a third ``Z2`` factor, giving a **16-element** group
        (``group_size = 16``).  This symmetry is only *approximate* (higher
        modes / tides break it weakly) -- the group-mixture wrapper fits the
        per-element weights from data and importance sampling corrects the
        residual, so nothing here needs it to be exact.  Default ``False``
        (the long-wavelength-exact 8-element group).
    polarisation_offset : float, optional
        Only used with ``polarisation_quarter``.  The canonical-point test in
        :meth:`in_fundamental_domain` picks the image with
        ``psi mod pi < pi/2`` -- an arbitrary seam, exactly like the sky's Z4
        wedge boundary that ``azimuth_offset`` moves.  If a run's actual ``psi`` posterior
        straddles that seam (its bulk sits near ``0`` or ``pi/2``), points on
        either side fold to *different* ``phase_step`` images even though
        they are the same continuous population -- an apparent bimodal
        ``(psi, phase)`` split that is really just the arbitrary zero-point
        cutting through the peak, not a second solution.  This shifts the
        seam: the test becomes
        ``(psi - polarisation_offset) mod pi < pi/2`` (this only changes
        which orbit representative is canonical -- the group action on the
        physical parameters is unchanged).  Prefer the data-driven, per-expert
        seams of :class:`AdaptiveFundamentalDomain`.  Default ``0.0``.
    """

    parameters = TRIANGULAR_DETECTOR_PARAMETERS
    group_size = TRIANGULAR_DETECTOR_GROUP_SIZE

    def __init__(
        self,
        reference_time,
        plane_normal,
        vertex,
        phase_reflection=False,
        azimuth_offset=0.0,
        polarisation_quarter=False,
        polarisation_offset=0.0,
    ):
        self.reference_time = float(reference_time)
        #: Shifts the psi-based seam ``in_fundamental_domain`` uses to pick
        #: the canonical ``phase_step`` image; see the class docstring.
        self.polarisation_offset = float(polarisation_offset)
        #: Fold the (2, 2)-mode polarisation/phase quarter turn
        #: ``{psi -> psi + pi/2, phase -> phase - pi/2}`` -- promotes the phase
        #: sector from a ``Z2`` (``phase -> phase + pi``, its square) to a
        #: ``Z4`` and doubles the group to 32.  Implies ``phase_reflection``.
        self.polarisation_quarter = bool(polarisation_quarter)
        self.phase_reflection = (
            bool(phase_reflection) or self.polarisation_quarter
        )
        #: In-plane rotation (rad) of the detector frame about the plane
        #: normal; moves the Z4 fundamental-domain seams off the sky peak.
        self.azimuth_offset = float(azimuth_offset)
        #: Instance attribute (shadows the class default): 32 with the
        #: polarisation/phase quarter turn, 16 with ``phase -> phase + pi``,
        #: else 8.
        self.group_size = (
            2 * TRIANGULAR_DETECTOR_GROUP_SIZE_PHASE
            if self.polarisation_quarter
            else TRIANGULAR_DETECTOR_GROUP_SIZE_PHASE
            if self.phase_reflection
            else TRIANGULAR_DETECTOR_GROUP_SIZE
        )
        self.gmst = _greenwich_mean_sidereal_time(self.reference_time)
        self.plane_normal = np.asarray(plane_normal, dtype=float)
        self._basis_np = _detector_frame_basis(
            self.plane_normal, self.azimuth_offset
        )
        self._basis = torch.as_tensor(self._basis_np, dtype=torch.float64)
        self.vertex = np.asarray(vertex, dtype=float)
        self._vertex = torch.as_tensor(self.vertex, dtype=torch.float64)

        # Equatorial (ra-based) Cartesian sky vector -> detector-frame vector,
        # with GMST folded in: ``w_f = R @ w_eq`` where
        # ``w_eq = (cos dec cos ra, cos dec sin ra, sin dec)`` and ``w_f`` is
        # ``(cos beta_f cos lam_f, cos beta_f sin lam_f, sin beta_f)`` -- the
        # same detector-frame direction :meth:`_to_frame` computes.  ``Rz``
        # maps ``ra -> ra - gmst``; ``_basis_np`` (rows e1, e2, e3=normal) then
        # rotates Earth-fixed -> detector frame.  Used by
        # :class:`RotatedAnglePair` (flow coordinates) and
        # :class:`PrimeSpaceTriangularGroupAction` (prime-space decode/encode).
        _g = self.gmst
        _Rz = np.array(
            [
                [np.cos(_g), np.sin(_g), 0.0],
                [-np.sin(_g), np.cos(_g), 0.0],
                [0.0, 0.0, 1.0],
            ]
        )
        self.sky_frame_rotation = self._basis_np @ _Rz

    # -- coordinate maps ------------------------------------------------

    def _to_frame(self, ra, dec, psi):
        """Equatorial ``(ra, dec, psi)`` -> detector-frame angles."""
        basis = self._basis.to(ra.dtype)
        phi = ra - self.gmst
        theta = 0.5 * np.pi - dec
        u, v, w = _uvw(phi, theta)
        m = -u * torch.sin(psi)[..., None] - v * torch.cos(psi)[..., None]
        w_f = w @ basis.T
        m_f = m @ basis.T
        theta_f = torch.acos(torch.clamp(w_f[..., 2], -1.0, 1.0))
        lam_f = torch.atan2(w_f[..., 1], w_f[..., 0])
        u_f, v_f, _ = _uvw(lam_f, theta_f)
        psi_f = _polarisation_angle(m_f, u_f, v_f)
        beta_f = 0.5 * np.pi - theta_f
        return lam_f, beta_f, psi_f

    def _from_frame(self, lam_f, beta_f, psi_f):
        """Detector-frame angles -> equatorial ``(ra, dec, psi)``."""
        basis = self._basis.to(lam_f.dtype)
        theta_f = 0.5 * np.pi - beta_f
        u_f, v_f, w_f = _uvw(lam_f, theta_f)
        sin_psi = torch.sin(psi_f)[..., None]
        cos_psi = torch.cos(psi_f)[..., None]
        m_f = -u_f * sin_psi - v_f * cos_psi
        w = w_f @ basis
        m = m_f @ basis
        dec = torch.asin(torch.clamp(w[..., 2], -1.0, 1.0))
        phi = torch.atan2(w[..., 1], w[..., 0])
        ra = torch.remainder(phi + self.gmst, _TWO_PI)
        u, v, _ = _uvw(ra - self.gmst, 0.5 * np.pi - dec)
        psi = torch.remainder(_polarisation_angle(m, u, v), np.pi)
        return ra, dec, psi

    def _geocenter_delay(self, ra, dec):
        """Geocenter-to-detector light-travel delay ``t_det - geocent_time``.

        Equal to ``-(n . r_det) / c`` with ``n`` the unit vector towards the
        source, matching bilby's ``time_delay_from_geocenter`` convention.
        """
        vertex = self._vertex.to(ra.dtype)
        phi = ra - self.gmst
        theta = 0.5 * np.pi - dec
        st = torch.sin(theta)
        n = torch.stack(
            [st * torch.cos(phi), st * torch.sin(phi), torch.cos(theta)],
            dim=-1,
        )
        return -(n * vertex).sum(-1) / _SPEED_OF_LIGHT

    # -- group action -------------------------------------------------

    def _decode(self, modes: torch.Tensor):
        """Split a mode index into ``(k, reflected, phase_step)``.

        ``k`` in ``0..3`` is the ``Z4`` sky rotation, ``reflected`` the ``Z2``
        detector-plane reflection.  ``phase_step`` is the phase-sector element:
        a bool ``phase -> phase + pi`` flag for the 8/16-element group, or an
        int ``0..3`` (``modes // 8``) for the 32-element polarisation/phase
        ``Z4`` -- ``{psi -> psi + step*pi/2, phase -> phase - step*pi/2}``
        (``step = 2`` reproduces the ``phase -> phase + pi`` flip).
        """
        k = torch.remainder(modes, 4).to(torch.float64)
        reflected = (
            torch.remainder(torch.div(modes, 4, rounding_mode="floor"), 2) == 1
        )
        step = torch.div(modes, 8, rounding_mode="floor")
        if self.polarisation_quarter:
            return k, reflected, torch.remainder(step, 4)
        return k, reflected, step == 1

    def _invert_modes(self, modes: torch.Tensor) -> torch.Tensor:
        """Index of the inverse element (the group is abelian)."""
        k = torch.remainder(modes, 4)
        refl = torch.remainder(torch.div(modes, 4, rounding_mode="floor"), 2)
        pf = torch.div(modes, 8, rounding_mode="floor")
        if self.polarisation_quarter:
            pf = torch.remainder(-pf, 4)
        return pf * 8 + refl * 4 + torch.remainder(-k, 4)

    # Public aliases of the mode helpers, for callers (e.g.
    # :class:`PrimeSpaceTriangularGroupAction`) that need to inspect group
    # elements without reaching into private names.
    def decode_modes(self, modes):
        """Split a mode index into ``(k, reflected, phase_step)``."""
        return self._decode(torch.as_tensor(modes))

    def invert_modes(self, modes):
        """Index of the inverse element (the group is abelian)."""
        return self._invert_modes(torch.as_tensor(modes))

    @property
    def mode_factor_sizes(self):
        """Sizes of the commuting cyclic factors, little-endian in the mode
        index (``k = modes % 4``, ``reflected = modes // 4 % 2``,
        ``phase_step = modes // 8``): ``[4, 2]`` for the 8-element group,
        ``[4, 2, 2]`` with ``phase_reflection``, ``[4, 2, 4]`` with
        ``polarisation_quarter``.  Passed to the group-mixture wrapper so it
        estimates the per-factor weight marginals independently (robust to
        transient mode collapse) rather than the flat 8/16/32 joint counts.
        """
        if self.polarisation_quarter:
            return [4, 2, 4]
        if self.phase_reflection:
            return [4, 2, 2]
        return [4, 2]

    def __call__(self, point_dict: dict, modes, inverse: bool = False) -> dict:
        """Apply the group element ``modes`` (or its inverse) to each point."""
        ra = point_dict["ra"]
        sin_dec = point_dict["sin_dec"]
        psi = point_dict["psi"]
        cos_theta_jn = point_dict["cos_theta_jn"]
        phase = point_dict["phase"]

        dec = torch.asin(torch.clamp(sin_dec, -1.0, 1.0))

        modes = torch.as_tensor(modes, device=ra.device)
        if inverse:
            modes = self._invert_modes(modes)
        k, reflected, phase_step = self._decode(modes)
        k = k.to(ra.dtype)
        quarter = 0.5 * np.pi * k

        lam_f, beta_f, psi_f = self._to_frame(ra, dec, psi)

        lam_f = lam_f + quarter
        beta_f = torch.where(reflected, -beta_f, beta_f)
        psi_f = torch.where(reflected, np.pi - psi_f, psi_f) + quarter
        # theta_jn -> pi - theta_jn under a reflection, i.e. a sign flip of
        # cos(theta_jn) -- unit Jacobian in this coordinate.
        cos_theta_jn = torch.where(
            reflected, -cos_theta_jn, cos_theta_jn
        )

        ra_t, dec_t, psi_t = self._from_frame(lam_f, beta_f, psi_f)

        if self.polarisation_quarter:
            # (2, 2)-mode polarisation/phase quarter turn:
            # psi -> psi + step*pi/2, phase -> phase - step*pi/2 (step in 0..3;
            # step == 2 is the phase -> phase + pi flip).
            shift = 0.5 * np.pi * phase_step.to(ra.dtype)
            psi_t = torch.remainder(psi_t + shift, np.pi)
            phase_t = torch.remainder(phase - shift, _TWO_PI)
        else:
            # Extra (2, 2)-mode reflection: phase -> phase + pi (16-element group).
            phase_t = torch.where(
                phase_step, torch.remainder(phase + np.pi, _TWO_PI), phase
            )

        out = {
            "ra": ra_t,
            "sin_dec": torch.sin(dec_t),
            "cos_theta_jn": cos_theta_jn,
            "psi": psi_t,
            "phase": phase_t,
        }

        # Physical-space path only: the sky degeneracy fixes the detector-frame
        # arrival time, not the geocentric one, so carry geocent_time along by
        # the change in the geocenter-to-detector delay (Santoliquido et al.
        # 2025, Eq. 22).  The prime-space adapter instead reparameterises to the
        # invariant detector-centre time and omits this key entirely (Tissino et
        # al. 2026, arXiv:2606.04918).
        if "geocent_time" in point_dict:
            out["geocent_time"] = (
                point_dict["geocent_time"]
                + self._geocenter_delay(ra, dec)
                - self._geocenter_delay(ra_t, dec_t)
            )

        return out

    def in_fundamental_domain(self, point_dict: dict) -> torch.Tensor:
        """Boolean mask: is each point the canonical point of its orbit?

        The canonical point is the one whose detector-frame azimuth lies in
        ``[0, pi / 2)`` and which sits on the ``beta >= 0`` side of the
        detector plane -- exactly one of the eight images of a generic point.
        With ``phase_reflection`` it is additionally the one with
        ``phase in [0, pi)`` -- one of the sixteen images.
        """
        dec = torch.asin(torch.clamp(point_dict["sin_dec"], -1.0, 1.0))
        lam_f, beta_f, _ = self._to_frame(
            point_dict["ra"], dec, point_dict["psi"]
        )
        in_quarter = torch.remainder(lam_f, _TWO_PI) < 0.5 * np.pi
        mask = in_quarter & (beta_f >= 0.0)
        if self.phase_reflection:
            mask = mask & (
                torch.remainder(point_dict["phase"], _TWO_PI) < np.pi
            )
        if self.polarisation_quarter:
            # phase-sector Z4: also fold (psi - polarisation_offset) to
            # [0, pi/2) -- the offset moves this seam off the psi peak (see
            # the class docstring / recommended_polarisation_offset).
            mask = mask & (
                torch.remainder(
                    point_dict["psi"] - self.polarisation_offset, np.pi
                ) < 0.5 * np.pi
            )
        return mask


def make_triangular_group_mixture_flow(
    reference_time,
    plane_normal,
    vertex,
    parameters=None,
    phase_reflection=False,
    azimuth_offset=0.0,
):
    """Build a group-mixture ``FlowModel`` class for a triangular detector.

    Thin wrapper around
    :func:`nessai.flowmodel.group_mixture.make_group_mixture_flow` bound to
    :class:`TriangularDetectorGroupAction`.

    Parameters
    ----------
    reference_time : float
        Geocentric GPS time of the event (see
        :class:`TriangularDetectorGroupAction`).
    plane_normal : array_like
        Earth-fixed unit normal to the detector plane.
    vertex : array_like
        Geocentric detector position (metres).
    parameters : list of str, optional
        Override the acted-on parameter names/order (default
        :data:`TRIANGULAR_DETECTOR_PARAMETERS`).  The flow must be given exactly
        these inputs, in this order.
    phase_reflection : bool, optional
        Fold in the extra ``phase -> phase + pi`` (2, 2)-mode degeneracy
        (16-element group).  See :class:`TriangularDetectorGroupAction`.

    Returns
    -------
    type
        A ``GroupMixtureFlowModel`` subclass, suitable as ``_FlowModelClass``
        of a :class:`nessai.flowmodel.group_mixture.GroupFlowProposal` (or the
        ``flow_class`` of a flow config).
    """
    from nessai.flowmodel.group_mixture import make_group_mixture_flow

    action = TriangularDetectorGroupAction(
        reference_time=reference_time,
        plane_normal=plane_normal,
        vertex=vertex,
        phase_reflection=phase_reflection,
        azimuth_offset=azimuth_offset,
    )
    names = list(parameters) if parameters is not None else action.parameters
    return make_group_mixture_flow(
        group_action_fn=action,
        group_size=action.group_size,
        param_names=names,
        in_fundamental_domain=action.in_fundamental_domain,
    )


# ---------------------------------------------------------------------------
# Prime-space adapter + proposal wiring
#
# nessai's :class:`~nessai.flowmodel.group_mixture.GroupFlowProposalMixin` can
# run :class:`TriangularDetectorGroupAction` directly in the *physical* parameter
# space and bridge to the flow's *prime* space with a
# :class:`~nessai.flowmodel.group_mixture.ReparamBridge` (non-affine
# reparameterisations handled exactly).  That is the ``prime_space=False`` path
# of :func:`make_triangular_group_flow_proposal` and needs no code here.
#
# The ``prime_space=True`` path instead maps the acted physical coordinates out
# of the nessai-gw prime vector, runs the unchanged group action, and re-encodes
# onto vectors of the *same* radii -- an exact unit-Jacobian prime-space map with
# no per-call numpy round-trip through the reparameterisation.  This mirrors the
# wiring tuned in the ``xG_inference`` ET replay optimisation.
# ---------------------------------------------------------------------------


def _angle_from_pair(x, y, scale):
    """Physical angle from a nessai ``Angle`` Cartesian pair (radius returned)."""
    radius = torch.hypot(x, y)
    angle = torch.remainder(torch.atan2(y, x), _TWO_PI) / scale
    return angle, radius


def _pair_from_angle(angle, radius, scale):
    """Inverse of :func:`_angle_from_pair`."""
    a = angle * scale
    return radius * torch.cos(a), radius * torch.sin(a)


def _decode_pair(point_dict, pair, scale):
    x, y = point_dict[pair[0]], point_dict[pair[1]]
    return _angle_from_pair(x, y, scale)


class PrimeSpaceTriangularGroupAction:
    """Apply :class:`TriangularDetectorGroupAction` in the nessai-gw *prime* space.

    Discovers the sky / ``psi`` / ``phase`` / ``theta_jn`` / ``t_det`` prime
    coordinates from the flow's actual ``prime_parameters`` and threads the
    acted subset through the unchanged group action, re-encoding onto
    same-radius vectors so the prime-space map is exactly a rotation /
    reflection / constant shift with unit Jacobian.  The detector-centre
    arrival time ``t_det`` is invariant under the group and is carried through
    untouched (Tissino et al. 2026, arXiv:2606.04918).

    Instances are passed to
    :func:`nessai.flowmodel.group_mixture.make_group_mixture_flow` as the
    ``prime_space_action`` / ``prime_space_in_domain`` pair.

    Parameters
    ----------
    action : TriangularDetectorGroupAction
        The physical-space group action.
    prime_names : list of str
        The flow's prime-parameter names, in order.  Re-bind after the proposal
        is initialised with :meth:`bind`.
    ellipse : nessai_gw._ellipse.PolarisationEllipse, optional
        Present when ``theta_jn`` uses the ``polarisation-ellipse``
        reparameterisation, whose prime coordinate is the residual
        ``(cos theta_jn - cos iota*(n)) / scale`` rather than the ``angle-sine``
        coordinate.  The residual is still odd under the plane reflection and
        invariant under the quarter turn, so the group action on it is
        unchanged; the ellipse is needed only to recover
        ``sign(cos theta_jn)`` for the ``delta_phase`` coordinate.
    ellipse_scale : float, optional
        The ``scale`` the reparameterisation was built with (default 1).
    """

    def __init__(self, action, prime_names, ellipse=None, ellipse_scale=1.0,
                 ellipse_coordinate="angle"):
        self._action = action
        # ``polarisation-ellipse``: the theta_jn prime is the residual
        # ``cos theta_jn - cos iota*(n)``, so ``sign(cos theta_jn)`` -- which the
        # delta_phase coordinate needs -- is no longer just ``-sign(u)``.  The
        # ellipse recovers it from the (already decoded) sky.
        self._ellipse = ellipse
        self._ellipse_scale = float(ellipse_scale)
        self._ellipse_coordinate = ellipse_coordinate
        # Flow sky coordinates are detector-frame (see RotatedAnglePair); the
        # decode/encode below work in equatorial coordinates, so rotate in and
        # out with the action's fixed sky-frame rotation.
        self._sky_R = torch.as_tensor(
            action.sky_frame_rotation, dtype=torch.float64
        )
        self.bind(prime_names)

    # -- binding -----------------------------------------------------------

    def bind(self, prime_names):
        """(Re)bind to the flow's actual prime-parameter order."""
        self._prime_names = list(prime_names)
        names = set(self._prime_names)

        # sky: ra_dec_{x,y,z} from the sky-ra-dec AnglePair (3-coord path) or
        # sky_u / sky_v from EqualAreaSky (2-coord path).
        self._sky = None
        self._sky2d = None
        if "sky_u" in names and "sky_v" in names:
            self._sky2d = ("sky_u", "sky_v")
        else:
            for prefix in ("ra_dec", "dec_ra"):
                trip = [f"{prefix}_{c}" for c in ("x", "y", "z")]
                if all(t in names for t in trip):
                    self._sky = tuple(trip)
                    break

        # psi: name_{x,y} from the angle-pi Angle reparam, or a single
        # ``psi_prime`` coordinate from SingleAngleReparameterisation.
        self._pair = {}
        for base in _ANGLE_SCALE:
            x, y = f"{base}_x", f"{base}_y"
            if x in names and y in names:
                self._pair[base] = (x, y)
        self._psi_single = (
            "psi_prime" in names and "psi" not in self._pair
        )

        # arg-alpha-beta: the two circular-polarisation phase coordinates
        # (ArgAlphaBetaReparameterisation).  When present they REPLACE both the
        # ``psi`` and ``delta_phase`` flow coordinates: they already fold the
        # polarisation-quarter Z4 (they are invariant under it), so the only
        # group action left on the phase sector is a joint ``+pi`` shift for the
        # odd sky-Z4 rotations and an ``alpha <-> beta`` swap under the plane
        # reflection -- applied directly in :meth:`_encode`.
        self._arg_ab = None
        if "arg_alpha" in names and "arg_beta" in names:
            self._arg_ab = ("arg_alpha", "arg_beta")

        # delta_phase: single linear polarisation-phase coordinate
        self._delta_phase = None
        for cand in ("delta_phase", "delta_phase_prime"):
            if cand in names:
                self._delta_phase = cand
                break

        # theta_jn: single linear angle-sine coordinate
        self._theta_jn = None
        for cand in ("theta_jn_prime", "theta_jn"):
            if cand in names:
                self._theta_jn = cand
                break

        # detector-centre arrival time: invariant, carried through unchanged
        # (detector-center-time reparameterisation).
        self._t_det = None
        for cand in ("t_det", "t_det_prime", "detector_time", "geocent_time"):
            if cand in names:
                self._t_det = cand
                break

        missing = []
        if self._sky is None and self._sky2d is None:
            missing.append("sky-ra-dec (ra_dec_x/_y/_z) or sky_u/sky_v")
        if self._arg_ab is None:
            if "psi" not in self._pair and not self._psi_single:
                missing.append("psi (psi_x/_y or psi_prime)")
            if self._delta_phase is None:
                missing.append("delta_phase")
        if self._theta_jn is None:
            missing.append("theta_jn")
        if self._t_det is None:
            missing.append("t_det")
        if missing:
            raise RuntimeError(
                f"prime space is missing {missing}, which the triangular-detector "
                "group action needs; the prime-space path only applies to a "
                "single-site triangular-detector run with the standard extrinsic parameters and "
                "the nessai-gw reparameterisations (sky-ra-dec, angle-pi / "
                "polarisation-phase or arg-alpha-beta, angle-sine, "
                "detector-center-time)."
            )

    # -- decode / encode -------------------------------------------------

    def _decode(self, point_dict):
        """nessai-gw prime dict -> ``TriangularDetectorGroupAction`` coordinate dict.

        Returns ``(acted, aux)`` where ``aux`` carries the radii needed to
        re-encode.
        """
        if self._sky2d is not None:
            # EqualAreaSky: (sky_u, sky_v) -> detector-frame unit vector.
            u = point_dict[self._sky2d[0]]
            v = point_dict[self._sky2d[1]]
            Rt = self._sky_R.to(u.dtype)
            lam_f = _TWO_PI * u
            z_f = torch.clamp(1.0 - 2.0 * v, -1.0, 1.0)
            rho = torch.sqrt(torch.clamp(1.0 - z_f * z_f, min=0.0))
            dx = rho * torch.cos(lam_f)
            dy = rho * torch.sin(lam_f)
            dz = z_f
            r_sky = torch.ones_like(u)
        else:
            dx, dy, dz = (point_dict[n] for n in self._sky)
            Rt = self._sky_R.to(dx.dtype)
            r_sky = torch.sqrt(dx * dx + dy * dy + dz * dz + _EPS)
        # detector-frame (flow) -> equatorial: v_eq = R^T v_det
        sx = Rt[0, 0] * dx + Rt[1, 0] * dy + Rt[2, 0] * dz
        sy = Rt[0, 1] * dx + Rt[1, 1] * dy + Rt[2, 1] * dz
        sz = Rt[0, 2] * dx + Rt[1, 2] * dy + Rt[2, 2] * dz
        norm = torch.sqrt(sx * sx + sy * sy + sz * sz + _EPS)
        ra = torch.remainder(torch.atan2(sy, sx), _TWO_PI)
        sin_dec = torch.clamp(sz / norm, -1.0, 1.0)

        if self._arg_ab is not None:
            # arg-alpha-beta: (arg_alpha, arg_beta) = ((phase - psi) / pi - 1,
            #                                          (phase + psi) / pi - 1).
            # Recover (psi, phase); the map is a bijection on
            # psi in [0, pi), phase in [0, 2*pi).  psi is fixed mod pi, phase
            # only mod pi -> pick the branch reproducing arg_alpha.
            au = torch.remainder(
                (point_dict[self._arg_ab[0]] + 1.0) * np.pi, _TWO_PI
            )
            av = torch.remainder(
                (point_dict[self._arg_ab[1]] + 1.0) * np.pi, _TWO_PI
            )
            psi = torch.remainder(0.5 * (av - au), np.pi)
            ph0 = torch.remainder(0.5 * (av + au), np.pi)
            e0 = torch.cos(torch.remainder(ph0 - psi, _TWO_PI) - au)
            e1 = torch.cos(torch.remainder(ph0 + np.pi - psi, _TWO_PI) - au)
            phase = torch.where(
                e1 > e0, torch.remainder(ph0 + np.pi, _TWO_PI), ph0
            )
            r_psi = torch.ones_like(ra)
        elif self._psi_single:
            ang = point_dict["psi_prime"]
            psi = torch.remainder(
                (ang + 1.0) * np.pi / _ANGLE_SCALE["psi"], np.pi
            )
            r_psi = torch.ones_like(psi)
        else:
            psi, r_psi = _decode_pair(
                point_dict, self._pair["psi"], _ANGLE_SCALE["psi"]
            )

        # theta_jn is decoupled from the frame rotation: the group only ever
        # sends cos(theta_jn) -> -cos(theta_jn) under a reflection, i.e. the
        # angle-sine coordinate ``u = 2 theta_jn / pi - 1`` -> ``-u`` (centre 0).
        # Handled directly in :meth:`_encode`; the value passed to the action is
        # a dummy.  ``sign(cos theta_jn) = -sign(u)`` is what the phase
        # coordinate needs.
        u_theta = point_dict[self._theta_jn]
        if self._ellipse is None:
            sign_ct = -torch.sign(u_theta)
        else:
            # residual coordinate: cos theta_jn = scale * u + cos iota*(n)
            cos_star = self._ellipse.cos_iota_torch(ra, sin_dec)
            # heteroskedastic residual: the reparameterisation divides by
            # s(|cos iota*|); undo it here so cos theta_jn -- and its sign --
            # come back exact.  s == 1 unless adaptive_width fitted a width.
            width = self._ellipse.residual_width_torch(
                torch.abs(torch.clamp(cos_star, -1.0, 1.0))
            )
            if self._ellipse_coordinate == "cos":
                cos_ct = self._ellipse_scale * width * u_theta + cos_star
            else:
                cos_ct = torch.cos(
                    u_theta * (0.5 * np.pi * self._ellipse_scale) * width
                    + torch.arccos(torch.clamp(cos_star, -1.0, 1.0))
                )
            sign_ct = torch.sign(cos_ct)
            sign_ct = torch.where(
                sign_ct == 0, torch.ones_like(sign_ct), sign_ct
            )
        cos_theta_jn = torch.zeros_like(ra)

        # The flow carries the single coordinate
        # ``delta_phase_prime = (delta_phase * scale mod 2*pi) / pi - 1`` with
        # ``delta_phase = phase + sign(cos theta_jn) * psi`` (polarisation-phase).
        # ``phase`` itself is group-invariant, so recover the invariant piece and
        # let :meth:`_encode` rebuild delta_phase from the group-transformed psi
        # and cos(theta_jn) sign.
        if self._arg_ab is None:
            delta_phase = torch.remainder(
                (point_dict[self._delta_phase] + 1.0)
                * np.pi
                / _DELTA_PHASE_SCALE,
                _TWO_PI,
            )
            phase = delta_phase - sign_ct * psi

        # The flow coordinate is the detector-centre arrival time (invariant
        # under the group), so it is not decoded here -- :meth:`_encode` copies
        # it through unchanged.

        acted = {
            "ra": ra,
            "sin_dec": sin_dec,
            "cos_theta_jn": cos_theta_jn,
            "psi": psi,
            "phase": phase,
        }
        aux = {
            "r_sky": r_sky,
            "r_psi": r_psi,
            "phase_inv": phase,
            "sign_ct": sign_ct,
        }
        return acted, aux

    def _encode(self, point_dict, mapped, aux):
        out = dict(point_dict)

        ra_t = mapped["ra"]
        sin_dec_t = torch.clamp(mapped["sin_dec"], -1.0, 1.0)
        cos_dec_t = torch.sqrt(torch.clamp(1.0 - sin_dec_t ** 2, min=0.0))
        # equatorial -> detector-frame (flow): v_det = R v_eq
        Rf = self._sky_R.to(cos_dec_t.dtype)
        ux = cos_dec_t * torch.cos(ra_t)
        uy = cos_dec_t * torch.sin(ra_t)
        uz = sin_dec_t
        dxf = Rf[0, 0] * ux + Rf[0, 1] * uy + Rf[0, 2] * uz
        dyf = Rf[1, 0] * ux + Rf[1, 1] * uy + Rf[1, 2] * uz
        dzf = Rf[2, 0] * ux + Rf[2, 1] * uy + Rf[2, 2] * uz
        if self._sky2d is not None:
            lam_f = torch.remainder(torch.atan2(dyf, dxf), _TWO_PI)
            z_f = torch.clamp(dzf, -1.0, 1.0)
            out[self._sky2d[0]] = lam_f / _TWO_PI
            out[self._sky2d[1]] = 0.5 * (1.0 - z_f)
        else:
            r = aux["r_sky"]
            sx, sy, sz = self._sky
            out[sx] = r * dxf
            out[sy] = r * dyf
            out[sz] = r * dzf

        if self._arg_ab is not None:
            pass  # psi is not a flow coordinate on this path
        elif self._psi_single:
            a = torch.remainder(
                mapped["psi"] * _ANGLE_SCALE["psi"], _TWO_PI
            )
            out["psi_prime"] = a / np.pi - 1.0
        else:
            px, py = self._pair["psi"]
            out[px], out[py] = _pair_from_angle(
                mapped["psi"], aux["r_psi"], _ANGLE_SCALE["psi"]
            )

        u = point_dict[self._theta_jn]
        out[self._theta_jn] = torch.where(aux["reflected"], -u, u)

        if self._arg_ab is not None:
            # Re-encode straight from the group-transformed (psi, phase):
            # arg_alpha = ((phase - psi) mod 2 pi) / pi - 1, likewise arg_beta.
            au = torch.remainder(mapped["phase"] - mapped["psi"], _TWO_PI)
            av = torch.remainder(mapped["phase"] + mapped["psi"], _TWO_PI)
            out[self._arg_ab[0]] = au / np.pi - 1.0
            out[self._arg_ab[1]] = av / np.pi - 1.0
            return {n: out[n] for n in self._prime_names}

        # delta_phase = phase_invariant + sign(cos theta_jn)_out * psi_out.
        # The reflection flips both sign(cos theta_jn) and psi (psi -> pi - psi,
        # via mapped["psi"]); a rotation leaves the sign and shifts psi; the
        # extra (2, 2) reflection adds pi to the invariant phase piece.
        sign_ct_out = torch.where(
            aux["reflected"], -aux["sign_ct"], aux["sign_ct"]
        )
        if self._action.polarisation_quarter:
            # phase sector Z4: the invariant phase piece shifts by
            # -step*pi/2; mapped["psi"] already carries +step*pi/2, so
            # delta_phase stays invariant for the face-on branch and shifts
            # by -step*pi for the face-off one.
            phase_inv_out = aux["phase_inv"] - 0.5 * np.pi * aux[
                "phase_step"
            ].to(aux["phase_inv"].dtype)
        else:
            phase_inv_out = torch.where(
                aux["phase_step"], aux["phase_inv"] + np.pi, aux["phase_inv"]
            )
        delta_phase_new = phase_inv_out + sign_ct_out * mapped["psi"]
        angle = torch.remainder(
            delta_phase_new * _DELTA_PHASE_SCALE, _TWO_PI
        )
        out[self._delta_phase] = angle / np.pi - 1.0

        # Detector-centre arrival time is group-invariant: carried through
        # unchanged from ``point_dict`` (via ``out = dict(point_dict)``).
        return {n: out[n] for n in self._prime_names}

    # -- interface ------------------------------------------------------

    def _mode_masks(self, modes, inverse):
        modes = torch.as_tensor(modes)
        if inverse:
            modes = self._action.invert_modes(modes)
        _, reflected, phase_step = self._action.decode_modes(modes)
        return reflected, phase_step

    def __call__(self, point_dict, modes, inverse: bool = False):
        acted, aux = self._decode(point_dict)
        mapped = self._action(acted, modes, inverse=inverse)
        aux["reflected"], aux["phase_step"] = self._mode_masks(
            modes, inverse
        )
        return self._encode(point_dict, mapped, aux)

    def in_fundamental_domain(self, point_dict):
        acted, aux = self._decode(point_dict)
        if self._arg_ab is not None:
            # (arg_alpha, arg_beta) are a bijective image of (psi, phase), so the
            # base predicate's raw psi / phase cuts (psi in [0, pi/2), phase in
            # [0, pi)) are genuine half-plane cuts in (arg_alpha, arg_beta) and
            # select exactly one image per orbit.
            return self._action.in_fundamental_domain(acted)
        if self._action.phase_reflection:
            # The base action folds the phase-reflection Z2 by testing
            # ``phase in [0, pi)`` on the raw invariant phase.  In prime space
            # the flow coordinate is ``delta_phase = phase + sign_ct * psi``,
            # not the raw phase, and psi is unconstrained -- so the raw-phase
            # cut is ~a coin flip w.r.t. delta_phase and never actually folds
            # the ``delta_phase -> delta_phase + pi`` (2, 2)-mode degeneracy the
            # base flow sees.  ``_encode`` under ``phase_flipped`` shifts
            # delta_phase by pi, so ``delta_phase in [0, pi)`` is the matching
            # fundamental domain -- test that instead (base uses ``phase`` only
            # for this clause).
            acted = dict(acted)
            acted["phase"] = acted["phase"] + aux["sign_ct"] * acted["psi"]
        return self._action.in_fundamental_domain(acted)


_LOG_2PI = float(np.log(2.0 * np.pi))
_HALF_LOG_2PI = 0.5 * _LOG_2PI


def _log_std_normal_pdf(x):
    return -0.5 * x * x - _HALF_LOG_2PI


class SkyOctantGaussianiser:
    """Cylindrical equal-area + probit map of the canonical sky octant.

    A ``canonical_transform`` for
    :class:`nessai.flowmodel.group_mixture.DiscreteGroupMixtureFlowWrapper`.
    Once the triangular-detector group has folded the sky to the axis-aligned
    detector-frame octant ``x, y, z >= 0`` (see
    :class:`~nessai_gw.reparameterisations.sky.RotatedAnglePair`), the base
    flow still sees the *uniform-on-sphere* prior restricted to that octant --
    a distribution with a hard edge along every octant boundary, which a
    Gaussian-latent flow fits badly.

    This transform replaces the three canonical Cartesian sky coordinates
    ``(x, y, z) = r * (sin th cos ph, sin th sin ph, cos th)`` with

    * ``a = Phi^-1( (2/pi) * ph )``      (azimuth ``ph in [0, pi/2)``  -> ``U`` -> ``N(0, 1)``)
    * ``b = Phi^-1( 1 - z / r )``        (``z/r = cos th in [0, 1]``   -> ``U`` -> ``N(0, 1)``)
    * ``c = r``                          (the auxiliary radius, passed through)

    ``(ph, z/r)`` are the equal-area (Lambert cylindrical) coordinates of the
    octant, so under the uniform-on-sphere prior ``a`` and ``b`` are *exactly*
    independent standard normals and the base flow sees no edge. The group
    action, the fundamental-domain predicate and every conjugation Jacobian
    stay in the untouched Cartesian frame -- this map only sits between the
    canonical representative and the base flow.

    The sky is detector-frame-rotated by ``RotatedAnglePair``, so the octant is
    already axis-aligned in the flow's ``ra_dec_{x,y,z}`` prime coordinates and
    no rotation is needed here.  ``reflect_parameters`` for the sky is
    incompatible with (and made redundant by) this transform: the octant walls
    are pushed to ``a, b -> -inf``.

    Jacobian (sky block only; all other coordinates are identity)::

        dx dy dz = r**2 dr dph d(z/r)             (spherical volume element)
        dph      = (pi/2) phi(a) da
        d(z/r)   = phi(b) db
        =>  log|d(a, b, c)/d(x, y, z)|
              = log(2/pi) - 2 log r - log phi(a) - log phi(b)
    """

    def __init__(self, param_names=None, eps: float = 1e-7):
        self._eps = float(eps)
        self._idx = None
        if param_names is not None:
            self.bind(param_names)

    def bind(self, param_names):
        names = list(param_names)
        trip = None
        for prefix in ("ra_dec", "dec_ra"):
            cand = [f"{prefix}_{c}" for c in ("x", "y", "z")]
            if all(c in names for c in cand):
                trip = cand
                break
        if trip is None:
            raise RuntimeError(
                "SkyOctantGaussianiser needs ra_dec_{x,y,z} (or dec_ra_*) in "
                f"the prime parameters; got {names}."
            )
        self._idx = [names.index(c) for c in trip]

    # -- transform ------------------------------------------------------

    def forward(self, canon):
        """``canon -> (t, log|det dt/dcanon|)`` (sky block gaussianised)."""
        ix, iy, iz = self._idx
        x, y, z = canon[:, ix], canon[:, iy], canon[:, iz]
        r = torch.sqrt(x * x + y * y + z * z + _EPS)
        lam = torch.atan2(y, x)
        u = torch.clamp((2.0 / np.pi) * lam, self._eps, 1.0 - self._eps)
        v = torch.clamp(1.0 - z / r, self._eps, 1.0 - self._eps)
        a = torch.special.ndtri(u)
        b = torch.special.ndtri(v)

        t = canon.clone()
        t[:, ix] = a
        t[:, iy] = b
        t[:, iz] = r
        log_j = (
            -np.log(np.pi / 2.0)
            - 2.0 * torch.log(r)
            - _log_std_normal_pdf(a)
            - _log_std_normal_pdf(b)
        )
        return t, log_j

    def inverse(self, t):
        """``t -> (canon, log|det dcanon/dt|)``."""
        ix, iy, iz = self._idx
        a, b, r = t[:, ix], t[:, iy], t[:, iz]
        u = torch.special.ndtr(a)
        v = torch.special.ndtr(b)
        lam = (np.pi / 2.0) * u
        cos_th = torch.clamp(1.0 - v, -1.0, 1.0)
        sin_th = torch.sqrt(torch.clamp(1.0 - cos_th * cos_th, min=0.0))
        rho = r * sin_th

        canon = t.clone()
        canon[:, ix] = rho * torch.cos(lam)
        canon[:, iy] = rho * torch.sin(lam)
        canon[:, iz] = r * cos_th
        log_j = (
            np.log(np.pi / 2.0)
            + 2.0 * torch.log(r)
            + _log_std_normal_pdf(a)
            + _log_std_normal_pdf(b)
        )
        return canon, log_j


_SKY_PROBIT_EPS = 1e-7


class SkyOctantProbit:
    """Probit of the folded equal-area sky sub-square (2-coordinate sky path).

    ``canonical_transform`` companion to
    :class:`nessai_gw.reparameterisations.sky.EqualAreaSky`.  After the
    triangular-detector group has folded the equal-area sky coordinates to the
    fundamental sub-square ``sky_u in [0, 1/4), sky_v in [0, 1/2)`` (the ``Z4``
    in-plane rotation acts by ``u -> u + k/4 mod 1`` and the ``Z2`` reflection
    by ``v -> 1 - v``), this maps that sub-square back to two independent
    standard normals::

        a = Phi^-1(4 * sky_u)          sky_u in [0, 1/4)  ->  N(0, 1)
        b = Phi^-1(2 * sky_v)          sky_v in [0, 1/2)  ->  N(0, 1)

    Under the uniform-on-sphere prior ``4 sky_u`` and ``2 sky_v`` are exactly
    ``U(0, 1)`` so ``a`` and ``b`` are exactly ``N(0, 1)`` and the base flow
    sees no octant edge.  There is **no radial coordinate**: unlike
    :class:`SkyOctantGaussianiser` this keeps the base-flow sky block 2-D.

    Jacobian (sky block only)::

        log|d(a, b)/d(sky_u, sky_v)| = log 8 - log phi(a) - log phi(b)

    ``u_scale`` / ``v_scale`` (default ``4`` / ``2``, the triangular fold) are
    the reciprocal widths of the sub-square; a sky that no group folds (e.g.
    the baseline-aligned sky of :mod:`nessai_gw.network_group`) uses ``1`` /
    ``1``, the probit of the whole unit square.
    """

    def __init__(self, param_names=None, u_scale=4.0, v_scale=2.0):
        self._iu = self._iv = None
        self.u_scale = float(u_scale)
        self.v_scale = float(v_scale)
        self._log_scale = float(np.log(self.u_scale * self.v_scale))
        if param_names is not None:
            self.bind(param_names)

    def bind(self, param_names):
        names = list(param_names)
        if "sky_u" not in names or "sky_v" not in names:
            raise RuntimeError(
                "SkyOctantProbit needs sky_u / sky_v in the prime parameters; "
                f"got {names}."
            )
        self._iu = names.index("sky_u")
        self._iv = names.index("sky_v")

    def forward(self, canon):
        """``canon -> (t, log|det dt/dcanon|)`` (sky block probit-mapped)."""
        iu, iv = self._iu, self._iv
        u = torch.clamp(
            self.u_scale * canon[:, iu], _SKY_PROBIT_EPS, 1.0 - _SKY_PROBIT_EPS
        )
        v = torch.clamp(
            self.v_scale * canon[:, iv], _SKY_PROBIT_EPS, 1.0 - _SKY_PROBIT_EPS
        )
        a = torch.special.ndtri(u)
        b = torch.special.ndtri(v)
        t = canon.clone()
        t[:, iu] = a
        t[:, iv] = b
        log_j = (
            self._log_scale
            - _log_std_normal_pdf(a)
            - _log_std_normal_pdf(b)
        )
        return t, log_j

    def inverse(self, t):
        """``t -> (canon, log|det dcanon/dt|)``."""
        iu, iv = self._iu, self._iv
        a, b = t[:, iu], t[:, iv]
        canon = t.clone()
        canon[:, iu] = torch.special.ndtr(a) / self.u_scale
        canon[:, iv] = torch.special.ndtr(b) / self.v_scale
        log_j = (
            -self._log_scale
            + _log_std_normal_pdf(a)
            + _log_std_normal_pdf(b)
        )
        return canon, log_j


class PhaseQuarterRecanonicaliser(torch.nn.Module):
    """Per-expert choice of fundamental domain for the polarisation/phase
    quarter-turn ``Z4`` -- a ``base_reparam`` for
    :class:`nessai.flowmodel.group_mixture.DiscreteGroupMixtureFlowWrapper`.

    The prime-space group folds the quarter turn ``(psi, phase) -> (psi +
    pi/2, phase - pi/2)`` on ``psi`` (``psi in [0, pi/2)``, ``delta_phase =
    phase + s psi in [0, pi)``, ``s = sign(cos theta_jn)``).  That is the
    right domain when the likelihood pins ``delta_phase`` and leaves ``psi``
    free.  Where it instead pins the raw ``phase`` (``psi`` still free -- the
    plateau regime of a co-sited triangle) the same fold cuts the single
    ``phase mod pi/2`` band into two parallel ``delta_phase``-vs-``psi``
    ridges half a period apart, one wrapping.  The other fundamental domain,
    ``D' = {psi in [0, pi), (phase - c) mod pi in [0, pi/2)}``, turns that
    into one axis-aligned band.  This module maps canonical points of ``D``
    onto ``D'`` (a quarter turn where needed plus the shear ``delta -> phase``:
    unit Jacobian), in the prime coordinates

        psi~' = psi' + k   in [-1, 1)
        p'    = ((delta' + 1) - s (psi~' + 1) / 2 - c) mod 1   in [0, 1/2)

    and is switched on per expert, each round, when the wrapped-angle spread
    of ``phase mod pi/2`` is well below that of ``delta_phase`` (each measured
    as a fraction of its own period), with hysteresis.  ``c`` centres the band
    in ``[0, 1/2)`` and is only moved when the band drifts ``recentre_tol``
    off centre, so the frame the base flow sees stays fixed between rounds.

    Out-of-``D'`` inputs to :meth:`inverse` get ``delta' = +1/2`` (``delta =
    3 pi / 2``), outside ``D``, so the wrapper's truncation rejects them.
    """

    #: Switch on when spread(phase mod pi/2) / spread(delta_phase) < this.
    on_ratio = 0.5
    #: Switch off when the ratio rises above this.
    off_ratio = 0.8
    #: Recentre ``c`` when the band centre is further than this from 1/4.
    recentre_tol = 0.1
    #: Fewer points than this: keep the current state.
    min_points = 50

    def __init__(self, param_names=None):
        super().__init__()
        self.register_buffer("_enabled", torch.zeros((), dtype=torch.bool))
        self.register_buffer("_cbar", torch.zeros((), dtype=torch.float64))
        self._idx = None
        if param_names is not None:
            self.bind(param_names)

    def bind(self, param_names):
        names = list(param_names)
        need = ("psi_prime", "delta_phase", "theta_jn_prime")
        missing = [n for n in need if n not in names]
        if missing:
            raise RuntimeError(
                f"PhaseQuarterRecanonicaliser needs {missing} in the prime "
                f"parameters; got {names}."
            )
        self._idx = tuple(names.index(n) for n in need)

    @property
    def enabled(self):
        return bool(self._enabled)

    def _parts(self, t):
        i_psi, i_dp, i_th = self._idx
        s = torch.where(t[:, i_th] > 0, -1.0, 1.0).to(t.dtype)
        return t[:, i_psi], t[:, i_dp], s, self._cbar.to(t.dtype)

    def forward(self, t):
        if not self.enabled:
            return t
        a, b, s, cbar = self._parts(t)
        k = (
            torch.remainder((b + 1) - s * (a + 1) / 2 - cbar, 1.0) >= 0.5
        ).to(t.dtype)
        psi_t = a + k
        p = torch.remainder((b + 1) - s * (psi_t + 1) / 2 - cbar, 1.0)
        out = t.clone()
        out[:, self._idx[0]] = psi_t
        out[:, self._idx[1]] = p
        return out

    def inverse(self, t):
        if not self.enabled:
            return t
        psi_t, p, s, cbar = self._parts(t)
        valid = (psi_t >= -1) & (psi_t < 1) & (p >= 0) & (p < 0.5)
        a = psi_t - (psi_t >= 0).to(t.dtype)
        b = torch.remainder(p + cbar + s * (psi_t + 1) / 2, 1.0) - 1
        b = torch.where(valid, b, torch.full_like(b, 0.5))
        out = t.clone()
        out[:, self._idx[0]] = a
        out[:, self._idx[1]] = b
        return out

    @staticmethod
    def _circ(y, period):
        """(wrapped-angle spread in radians, circular mean in ``y`` units)."""
        z = np.mean(np.exp(2j * np.pi * y / period))
        r = max(abs(z), 1e-12)
        return float(np.sqrt(-2.0 * np.log(r))), float(
            np.mod(np.angle(z) * period / (2 * np.pi), period)
        )

    @torch.no_grad()
    def update(self, t):
        """Refit on this round's claimed base-frame points ``t`` (in ``D``);
        return ``True`` if the frame changed."""
        if t.shape[0] < self.min_points:
            return False
        i_psi, i_dp, i_th = self._idx
        tn = t.detach().cpu().double().numpy()
        a, b = tn[:, i_psi], tn[:, i_dp]
        s = np.where(tn[:, i_th] > 0, -1.0, 1.0)
        p0 = np.mod((b + 1) - s * (a + 1) / 2, 0.5)
        sp_phase, centre = self._circ(p0, 0.5)
        sp_delta, _ = self._circ(b + 1, 1.0)
        ratio = sp_phase / max(sp_delta, 1e-12)
        was = self.enabled
        changed = False
        if not was and ratio < self.on_ratio:
            self._enabled.fill_(True)
            self._cbar.fill_(float(np.mod(centre - 0.25, 0.5)))
            changed = True
        elif was and ratio > self.off_ratio:
            self._enabled.fill_(False)
            changed = True
        elif was:
            off = float(np.mod(centre - float(self._cbar), 0.5))
            if abs(off - 0.25) > self.recentre_tol:
                self._cbar.fill_(float(np.mod(centre - 0.25, 0.5)))
                changed = True
        logger.info(
            "Phase-quarter recanon: spread(phase mod pi/2)/spread(delta_phase)"
            " = %.3f/%.3f = %.3f (on < %.2f, off > %.2f), n=%d, %s%s",
            sp_phase, sp_delta, ratio, self.on_ratio, self.off_ratio,
            t.shape[0], "ON" if self.enabled else "off",
            (" [switched]" if was != self.enabled
             else " [recentred]" if changed else ""),
        )
        return changed


class AdaptiveFundamentalDomain(torch.nn.Module):
    """Per-expert, data-driven choice of fundamental domain -- a
    ``base_reparam`` for
    :class:`nessai.flowmodel.group_mixture.DiscreteGroupMixtureFlowWrapper`.

    The group mixture folds every point into one fixed fundamental domain
    ``D0`` (prime coordinates ``sky_u in [0, 1/4)``, ``sky_v <= 1/2``,
    ``psi_prime in [-1, 0)``, ``delta_phase in [-1, 0)``).  Its periodic cuts
    are arbitrary: a posterior peak sitting on one is cut in two and the base
    flow has to model both halves glued to opposite walls.  This module maps
    each canonical point to its image in a *shifted* domain whose seams sit
    where the expert's folded posterior has the least mass, and expresses it
    in seam-relative coordinates, so the base flow sees the peak whole:

    * sky: ``(sky_u - c_u) mod 1 in [0, 1/4)`` (the Z4 rotation);
    * polarisation/phase sector, one of two domain families:

      - ``"delta"`` (``delta_phase`` pinned, ``psi`` free):
        ``(psi' + 1 - c_psi) mod 2 in [0, 1)`` and
        ``(delta' + 1 - c_delta) mod 2 in [0, 1)``;
      - ``"phase"`` (raw phase pinned -- the co-sited-triangle plateau
        regime, see :class:`PhaseQuarterRecanonicaliser`): the quarter turn is
        folded on the phase instead, ``(phase/pi - c_phase) mod 2 in [0, 1/2)``,
        ``psi`` kept over its full period (``(psi' + 1 - c_psi) mod 2``),
        and the ``delta_phase`` slot carries ``(phase/pi - c_phase) mod 2``.

    Any seam positions give a valid fundamental domain (each clause fixes one
    commuting factor of the group), so the map ``D0 -> D`` is "apply the
    unique group element taking the point into ``D``" followed by per-
    coordinate translations (and, for ``"phase"``, a unit shear): unit
    Jacobian, exact.  The group element is found with the real prime-space
    action: the sky rotation from ``sky_u`` in closed form, then the four
    polarisation/phase-sector candidates (brute force over the whole group
    as a fall-back).  ``inverse`` maps inputs outside the target box to
    ``delta_phase = +1/2`` (outside ``D0``) so truncation rejects them.

    :meth:`update` (each training round, on the expert's own canonical
    points) picks the family from the wrapped spreads of ``phase mod pi/2``
    vs ``delta_phase mod pi`` (``on_ratio`` / ``off_ratio`` hysteresis, only
    when ``allow_phase_mode``), then each seam at the minimum of a smoothed
    circular histogram of the corresponding folded coordinate, in the order
    sky -> polarisation/phase (the latter measured on points already moved to
    the chosen sky domain).  A seam only moves when the density at its current
    position exceeds ``move_density`` (relative to uniform) *and*
    ``move_factor`` times the minimum -- a seam in an empty or flat region is
    left alone, so the base-flow frame stays fixed between rounds.
    """

    on_ratio = 0.5
    off_ratio = 0.8
    n_bins = 64
    smooth_bins = 2.0
    move_density = 0.25
    move_factor = 2.0
    min_points = 50

    def __init__(self, action, param_names=None, allow_phase_mode=False):
        super().__init__()
        self._action = action
        self.allow_phase_mode = bool(allow_phase_mode)
        # (c_u, c_psi, c_delta, c_phase) in prime units
        self.register_buffer("_seams", torch.zeros(4, dtype=torch.float64))
        self.register_buffer("_phase_mode", torch.zeros((), dtype=torch.bool))
        self.register_buffer("_seen", torch.zeros((), dtype=torch.bool))
        self._names = None
        if param_names is not None:
            self.bind(param_names)

    def bind(self, param_names):
        names = list(param_names)
        need = ("sky_u", "sky_v", "psi_prime", "delta_phase", "theta_jn_prime")
        missing = [n for n in need if n not in names]
        if missing:
            raise RuntimeError(
                f"AdaptiveFundamentalDomain needs {missing} in the prime "
                f"parameters; got {names}."
            )
        self._names = names
        self._iu, self._iv, self._ipsi, self._idp, self._ith = (
            names.index(n) for n in need
        )

    # -- state -------------------------------------------------------------
    def _state(self):
        return tuple(float(c) for c in self._seams), bool(self._phase_mode)

    def _identity(self):
        seams, phase = self._state()
        return not phase and not any(seams)

    # -- geometry ------------------------------------------------------------
    def _s(self, z):
        return torch.where(z[:, self._ith] > 0, -1.0, 1.0).to(z.dtype)

    def _phi_n(self, z):
        """``phase / pi mod 2`` from the prime ``(psi', delta', theta')``."""
        return torch.remainder(
            (z[:, self._idp] + 1) - self._s(z) * (z[:, self._ipsi] + 1) / 2, 2.0
        )

    def _in_target(self, z, seams, phase_mode):
        cu, cpsi, cdel, cphi = seams
        ok = torch.remainder(z[:, self._iu] - cu, 1.0) < 0.25
        ok = ok & (z[:, self._iv] <= 0.5)
        if phase_mode:
            ok = ok & (torch.remainder(self._phi_n(z) - cphi, 2.0) < 0.5)
        else:
            ok = ok & (torch.remainder(z[:, self._ipsi] + 1 - cpsi, 2.0) < 1.0)
            ok = ok & (torch.remainder(z[:, self._idp] + 1 - cdel, 2.0) < 1.0)
        return ok

    def _act(self, z, modes):
        d = {n: z[:, i] for i, n in enumerate(self._names)}
        out = self._action(d, modes, inverse=False)
        return torch.stack([out[n] for n in self._names], dim=1)

    def _map_to(self, z, seams, phase_mode):
        """Image of each row of ``z`` in the target domain, and a found mask."""
        out = z.clone()
        found = torch.zeros(z.shape[0], dtype=torch.bool, device=z.device)
        if z.shape[0] == 0:
            return out, found
        cu = seams[0]
        k = torch.remainder(
            -torch.floor(4.0 * torch.remainder(z[:, self._iu] - cu, 1.0)), 4
        ).long()
        for j in range(4):
            cand = self._act(z, k + 8 * j)
            m = self._in_target(cand, seams, phase_mode) & ~found
            out[m] = cand[m]
            found |= m
        if not bool(found.all()):
            rest = (~found).nonzero(as_tuple=True)[0]
            zr = z[rest]
            fr = torch.zeros(len(rest), dtype=torch.bool, device=z.device)
            for g in range(self._action._action.group_size):
                cand = self._act(zr, torch.full_like(rest, g))
                m = self._in_target(cand, seams, phase_mode) & ~fr
                out[rest[m]] = cand[m]
                fr |= m
            found[rest] = fr
        return out, found

    def _to_box(self, z, seams, phase_mode):
        cu, cpsi, cdel, cphi = seams
        y = z.clone()
        y[:, self._iu] = torch.clamp(
            torch.remainder(z[:, self._iu] - cu, 1.0), max=0.25 * (1 - 1e-7)
        )
        y[:, self._ipsi] = torch.remainder(z[:, self._ipsi] + 1 - cpsi, 2.0) - 1
        if phase_mode:
            y[:, self._idp] = torch.remainder(self._phi_n(z) - cphi, 2.0)
        else:
            y[:, self._idp] = torch.remainder(z[:, self._idp] + 1 - cdel, 2.0) - 1
        return y

    def _box_valid(self, y, phase_mode):
        u, v = y[:, self._iu], y[:, self._iv]
        a, b = y[:, self._ipsi], y[:, self._idp]
        ok = (u >= 0) & (u < 0.25) & (v >= 0) & (v <= 0.5)
        if phase_mode:
            return ok & (a >= -1) & (a < 1) & (b >= 0) & (b < 0.5)
        return ok & (a >= -1) & (a < 0) & (b >= -1) & (b < 0)

    def _from_box(self, y, seams, phase_mode):
        cu, cpsi, cdel, cphi = seams
        z = y.clone()
        z[:, self._iu] = torch.remainder(y[:, self._iu] + cu, 1.0)
        psi = torch.remainder(y[:, self._ipsi] + 1 + cpsi, 2.0) - 1
        z[:, self._ipsi] = psi
        if phase_mode:
            z[:, self._idp] = torch.remainder(
                y[:, self._idp] + cphi + self._s(y) * (psi + 1) / 2, 2.0
            ) - 1
        else:
            z[:, self._idp] = torch.remainder(y[:, self._idp] + 1 + cdel, 2.0) - 1
        return z

    # -- base_reparam interface ---------------------------------------------
    def forward(self, canon):
        if self._identity():
            return canon
        seams, phase = self._state()
        z, _ = self._map_to(canon, seams, phase)
        return self._to_box(z, seams, phase)

    def inverse(self, y):
        if self._identity():
            return y
        seams, phase = self._state()
        valid = self._box_valid(y, phase)
        z = self._from_box(y, seams, phase)
        canon, found = self._map_to(z, (0.0, 0.0, 0.0, 0.0), False)
        bad = ~(valid & found)
        if bool(bad.any()):
            canon[bad, self._idp] = 0.5
        return canon

    # -- seam / family choice ------------------------------------------------
    @staticmethod
    def _circ_spread(y, period):
        z = np.mean(np.exp(2j * np.pi * y / period))
        return float(np.sqrt(-2.0 * np.log(max(abs(z), 1e-12))))

    def _density(self, vals, period):
        """Smoothed circular histogram (mean 1) on ``n_bins`` bin centres."""
        n = self.n_bins
        h, _ = np.histogram(np.mod(vals, period), bins=n, range=(0.0, period))
        k = np.arange(n) - n // 2
        ker = np.exp(-0.5 * (k / self.smooth_bins) ** 2)
        ker = np.roll(ker / ker.sum(), -(n // 2))
        dens = np.real(np.fft.ifft(np.fft.fft(h) * np.fft.fft(ker)))
        return dens / max(dens.mean(), 1e-300)

    def _choose_seam(self, vals, period, current, force=False):
        dens = self._density(vals, period)
        n = self.n_bins
        i_min = int(np.argmin(dens))
        best = (i_min + 0.5) * period / n
        i_cur = int(np.floor(np.mod(current, period) / period * n)) % n
        d_cur = float(dens[i_cur])
        if force or (
            d_cur > self.move_density
            and d_cur > self.move_factor * float(dens[i_min])
        ):
            return best, d_cur, float(dens[i_min])
        return float(current), d_cur, float(dens[i_min])

    @torch.no_grad()
    def update(self, canon):
        if canon.shape[0] < self.min_points:
            return False
        before = self._state()
        (cu, cpsi, cdel, cphi), phase = before
        was_seen = bool(self._seen)

        u = canon[:, self._iu].double().cpu().numpy()
        cu, du, _ = self._choose_seam(4.0 * u, 1.0, 4.0 * cu)
        cu = cu / 4.0

        z1, _ = self._map_to(canon, (cu, 0.0, 0.0, 0.0), False)
        phi_n = self._phi_n(z1).double().cpu().numpy()
        dn = (z1[:, self._idp] + 1).double().cpu().numpy()
        sp_phase = self._circ_spread(phi_n, 0.5)
        sp_delta = self._circ_spread(dn, 1.0)
        ratio = sp_phase / max(sp_delta, 1e-12)
        new_phase = phase
        if self.allow_phase_mode:
            if not phase and ratio < self.on_ratio:
                new_phase = True
            elif phase and ratio > self.off_ratio:
                new_phase = False
        switched = new_phase != phase

        if new_phase:
            cphi, dphi, _ = self._choose_seam(
                phi_n, 0.5, cphi, force=switched or not was_seen
            )
            z2, _ = self._map_to(canon, (cu, 0.0, 0.0, cphi), True)
            psi = (z2[:, self._ipsi] + 1).double().cpu().numpy()
            cpsi, dpsi, _ = self._choose_seam(psi, 2.0, 0.0 if switched else cpsi)
            cdel, ddel = 0.0, float("nan")
        else:
            psi = (z1[:, self._ipsi] + 1).double().cpu().numpy()
            cpsi, dpsi, _ = self._choose_seam(psi, 1.0, 0.0 if switched else cpsi)
            z2, _ = self._map_to(canon, (cu, cpsi, 0.0, 0.0), False)
            dl = (z2[:, self._idp] + 1).double().cpu().numpy()
            cdel, ddel, _ = self._choose_seam(dl, 1.0, 0.0 if switched else cdel)
            cphi, dphi = 0.0, float("nan")

        self._seams.copy_(torch.tensor([cu, cpsi, cdel, cphi], dtype=torch.float64))
        self._phase_mode.fill_(bool(new_phase))
        self._seen.fill_(True)
        after = self._state()
        changed = (
            after[1] != before[1]
            or any(abs(a - b) > 1e-12 for a, b in zip(after[0], before[0]))
        )
        logger.info(
            "Adaptive domain: %s-folded (phase/delta spread ratio %.3f), seams "
            "sky_u %.4f psi %.4f delta %.4f phase %.4f; density at old seams "
            "sky %.2f psi %.2f delta %.2f phase %.2f (x uniform), n=%d%s",
            "phase" if new_phase else "delta", ratio, cu, cpsi, cdel, cphi,
            du, dpsi, ddel, dphi, canon.shape[0],
            " [changed]" if changed else "",
        )
        return changed


def _lerp_cdf(x, edges, cdf):
    """Piecewise-linear CDF value at ``x`` (``edges``/``cdf`` 1-D, monotone)."""
    n = edges.numel() - 1
    du = edges[1] - edges[0]
    i = torch.clamp(((x - edges[0]) / du).floor().long(), 0, n - 1)
    frac = (x - edges[i]) / du
    return cdf[i] + frac * (cdf[i + 1] - cdf[i]), i


def _invert_cdf(y, edges, cdf):
    """Inverse of :func:`_lerp_cdf`: ``x`` such that ``lerp_cdf(x) == y``."""
    i = torch.clamp(torch.searchsorted(cdf, y, right=True) - 1, 0, cdf.numel() - 2)
    span = cdf[i + 1] - cdf[i]
    frac = torch.where(span > 0, (y - cdf[i]) / span, torch.zeros_like(y))
    return edges[i] + frac * (edges[i + 1] - edges[i]), i


class SkyOctantPullback:
    r"""Prior-pullback PIT of the folded equal-area sky sub-square.

    Drop-in replacement for :class:`SkyOctantProbit` (same
    ``canonical_transform`` contract, same ``sky_u`` / ``sky_v`` prime
    coordinates) that maps the fundamental sub-square
    ``sky_u in [0, 1/4), sky_v in [0, 1/2)`` to two standard normals through the
    **exact 2-D probability-integral transform of a supplied density**
    ``q(sky_u, sky_v)`` rather than the uniform one::

        u1 = F_u(sky_u)            (marginal CDF of q in sky_u)
        u2 = F_{v|u}(sky_v)        (conditional CDF of q in sky_v given the
                                    sky_u cell)
        a  = Phi^-1(u1),   b = Phi^-1(u2)

    The intended ``q`` is the note's analytic prior-pullback sky density
    (arXiv:.../triangle_degeneracy; the frozen-(2, 2) marginal likelihood
    ``exp(sky_density.lnp)``, weighted by the volumetric prior, then **folded to
    the fundamental domain** -- sum of the eight group images).  On the octomodal
    ET BNS posterior the folded ``q`` predicts the folded sky posterior to
    KL ~= 0.5 nat (vs ~2.2 nat for the uniform sub-square), so the base flow only
    has to learn the small residual + the true (weak) localisation on top.

    ``q`` is passed in as a dense grid of **cell-centre densities**
    ``q_grid[i, j]`` over ``sky_u in [0, 1/4)`` x ``sky_v in [0, 1/2)`` (uniform
    cells).  It need not be normalised.  The Jacobian uses the piecewise-constant
    density that is *exactly* the derivative of the piecewise-linear CDFs built
    from the same grid, so the map and ``log_j`` are consistent::

        log|d(a, b)/d(sky_u, sky_v)| = log q_hat(sky_u, sky_v)
                                       - log phi(a) - log phi(b)

    with ``q_hat`` the (normalised) piecewise-constant density.

    Parameters
    ----------
    q_grid : array_like
        ``(Nu, Nv)`` non-negative folded-``q`` density at the centres of a
        uniform grid over ``sky_u in [0, 1/4)`` x ``sky_v in [0, 1/2)``.
    param_names : list of str, optional
        Prime-parameter names; must contain ``sky_u`` and ``sky_v``.  Bind later
        with :meth:`bind` if not given.
    """

    def __init__(self, q_grid, param_names=None):
        q = np.asarray(q_grid, dtype=float)
        if q.ndim != 2:
            raise ValueError(f"q_grid must be 2-D, got shape {q.shape}")
        nu, nv = q.shape
        du, dv = 0.25 / nu, 0.5 / nv
        q = np.clip(q, 0.0, None)
        norm = q.sum() * du * dv
        if not norm > 0:
            raise ValueError("q_grid integrates to zero.")
        q = q / norm

        m_u = q.sum(axis=1) * dv                      # marginal density in sky_u
        C_u = np.concatenate([[0.0], np.cumsum(m_u) * du])
        C_u /= C_u[-1]
        cond = q / np.clip(q.sum(axis=1, keepdims=True) * dv, 1e-300, None)
        C_v = np.concatenate(
            [np.zeros((nu, 1)), np.cumsum(cond, axis=1) * dv], axis=1
        )
        C_v /= C_v[:, -1:]

        self._nu, self._nv = nu, nv
        self._u_edges = torch.as_tensor(
            np.linspace(0.0, 0.25, nu + 1), dtype=torch.float64
        )
        self._v_edges = torch.as_tensor(
            np.linspace(0.0, 0.5, nv + 1), dtype=torch.float64
        )
        self._C_u = torch.as_tensor(C_u, dtype=torch.float64)
        self._C_v = torch.as_tensor(C_v, dtype=torch.float64)
        self._log_m_u = torch.as_tensor(np.log(m_u), dtype=torch.float64)
        self._log_cond = torch.as_tensor(
            np.log(np.clip(cond, 1e-300, None)), dtype=torch.float64
        )
        self._iu = self._iv = None
        if param_names is not None:
            self.bind(param_names)

    def bind(self, param_names):
        names = list(param_names)
        if "sky_u" not in names or "sky_v" not in names:
            raise RuntimeError(
                "SkyOctantPullback needs sky_u / sky_v in the prime "
                f"parameters; got {names}."
            )
        self._iu = names.index("sky_u")
        self._iv = names.index("sky_v")

    def _dtype_cast(self, ref):
        return (
            self._u_edges.to(ref.dtype), self._v_edges.to(ref.dtype),
            self._C_u.to(ref.dtype), self._C_v.to(ref.dtype),
            self._log_m_u.to(ref.dtype), self._log_cond.to(ref.dtype),
        )

    def forward(self, canon):
        iu, iv = self._iu, self._iv
        ue, ve, Cu, Cv, log_mu, log_cond = self._dtype_cast(canon)
        su = torch.clamp(canon[:, iu], _SKY_PROBIT_EPS, 0.25 - _SKY_PROBIT_EPS)
        sv = torch.clamp(canon[:, iv], _SKY_PROBIT_EPS, 0.5 - _SKY_PROBIT_EPS)

        u1, iu_cell = _lerp_cdf(su, ue, Cu)
        dvv = ve[1] - ve[0]
        jv = torch.clamp(((sv - ve[0]) / dvv).floor().long(), 0, self._nv - 1)
        frac_v = (sv - ve[jv]) / dvv
        row = Cv[iu_cell]
        u2 = torch.gather(row, 1, jv[:, None])[:, 0] + frac_v * (
            torch.gather(row, 1, (jv + 1)[:, None])[:, 0]
            - torch.gather(row, 1, jv[:, None])[:, 0]
        )

        a = torch.special.ndtri(torch.clamp(u1, _SKY_PROBIT_EPS, 1 - _SKY_PROBIT_EPS))
        b = torch.special.ndtri(torch.clamp(u2, _SKY_PROBIT_EPS, 1 - _SKY_PROBIT_EPS))
        t = canon.clone()
        t[:, iu] = a
        t[:, iv] = b
        log_q = log_mu[iu_cell] + torch.gather(
            log_cond[iu_cell], 1, jv[:, None]
        )[:, 0]
        log_j = log_q - _log_std_normal_pdf(a) - _log_std_normal_pdf(b)
        return t, log_j

    def inverse(self, t):
        iu, iv = self._iu, self._iv
        ue, ve, Cu, Cv, log_mu, log_cond = self._dtype_cast(t)
        a, b = t[:, iu], t[:, iv]
        u1 = torch.clamp(torch.special.ndtr(a), _SKY_PROBIT_EPS, 1 - _SKY_PROBIT_EPS)
        u2 = torch.clamp(torch.special.ndtr(b), _SKY_PROBIT_EPS, 1 - _SKY_PROBIT_EPS)

        su, iu_cell = _invert_cdf(u1, ue, Cu)
        row = Cv[iu_cell]
        jv = torch.clamp(
            torch.searchsorted(row, u2[:, None], right=True)[:, 0] - 1,
            0, self._nv - 2,
        )
        c0 = torch.gather(row, 1, jv[:, None])[:, 0]
        c1 = torch.gather(row, 1, (jv + 1)[:, None])[:, 0]
        span = c1 - c0
        frac = torch.where(span > 0, (u2 - c0) / span, torch.zeros_like(u2))
        sv = ve[jv] + frac * (ve[jv + 1] - ve[jv])

        canon = t.clone()
        canon[:, iu] = su
        canon[:, iv] = sv
        log_q = log_mu[iu_cell] + torch.gather(
            log_cond[iu_cell], 1, jv[:, None]
        )[:, 0]
        log_j = -log_q + _log_std_normal_pdf(a) + _log_std_normal_pdf(b)
        return canon, log_j


def triangular_group_reparameterisations(
    sampling_parameters,
    reference_time,
    vertex=None,
    phase_coordinates="polarisation-phase",
    polarisation_ellipse=None,
    polarisation_ellipse_scale=1.0,
    polarisation_ellipse_coordinate="angle",
    polarisation_ellipse_adaptive_width=False,
    chirp_distance=False,
    chirp_distance_plane_normal=None,
    chirp_distance_azimuth_offset=0.0,
    chirp_distance_k0=None,
    chirp_distance_fiducial=None,
):
    """Reparameterisation overrides that keep the acted parameters isometric.

    The triangular-detector group action has unit Jacobian in
    ``(ra, sin_dec, cos_theta_jn, psi, phase, geocent_time)``.  Each of those
    maps to the nessai-gw prime coordinates by an isometry *provided* the right
    reparameterisation is used:

    * ``chi_1`` / ``chi_2`` -> ``aligned-spin`` (nessai-gw CDF -> inverse-normal
      map; standard-normal prime prior, removes the log cusp at ``chi = 0``).
    * ``lambda_1`` / ``lambda_2`` -> ``logit`` with ``update_bounds=False``
      (fixed hard bounds, prime coordinate on the whole real line).
    * ``theta_jn`` -> ``angle-sine`` with ``update_bounds=False``.  The fixed,
      symmetric bounds keep the group's ``theta_jn -> pi - theta_jn`` reflection
      an exact sign flip of the prime coordinate; ``update_bounds=True`` would
      let the empirical bounds drift off ``pi/2`` and break that.
    * ``geocent_time`` -> ``detector-center-time``: the flow coordinate is the
      (affine-rescaled) arrival time at the detector centre,
      ``t_det = geocent_time + delay(ra, dec)``, which is **invariant** under the
      group -- so :class:`PrimeSpaceTriangularGroupAction` carries it through
      untouched and time is not acted on at all (Tissino et al. 2026,
      arXiv:2606.04918).  Constant ``reference_time`` shift and fixed
      :data:`_GEOCENT_SCALE` keep the GPS epoch off the flow.
    * ``phase`` -> ``polarisation-phase``: a **single** ``[-1, 1)`` coordinate
      ``delta_phase = phase + sign(cos theta_jn) * psi``, making the
      likelihood-constrained polarisation/phase combination an explicit flow
      axis instead of a thin diagonal ridge across four prime coordinates -- and
      *without* the ``Angle`` pair's free ``chi(2)`` radius, whose scale mixing
      with a well-measured ridge left a leptokurtic origin cusp the base flow
      fit poorly.  ``psi`` (``angle-pi``) and ``theta_jn`` (``angle-sine``) are
      prerequisites of this coordinate.
    * ``luminosity_distance`` -> ``chirp-distance`` (only if ``chirp_distance``
      is set): the Roulet et al. 2022 (arXiv:2207.03508, Eqs. 9, 18) coordinate
      ``chirp_distance = luminosity_distance / (chirp_mass^{5/6} |R_k0|)``,
      which strips out the dominant-mode antenna-pattern amplitude at a fixed
      reference detector ``k0`` -- removing the ``luminosity_distance`` <->
      ``theta_jn`` degeneracy that otherwise dominates a single triangular
      detector's posterior (``corr = 0.998`` on the unreparameterised
      ET-Delta coordinate).  ``chirp_mass`` (``mass``), ``theta_jn`` and
      ``ra``/``dec``/``psi`` are prerequisites, so this is ranked ahead of
      everything else in the returned dict.

    Every other parameter is left to
    :meth:`nessai_gw.proposals.GWReparamMixin.add_default_reparameterisations`
    (``sky-ra-dec`` for ``ra``/``dec``, ``angle-pi`` for ``psi``,
    ``distance`` / ``mass`` for the intrinsic parameters, ...).

    This is independent of the group size: with a 16-element action
    (``phase_reflection=True``) the mixture folds ``phase <-> phase + pi``, so
    ``polarisation-phase`` stays at its default (bijective) period ``2*pi``.

    Parameters
    ----------
    sampling_parameters : iterable of str
        Every parameter nessai samples.
    reference_time : float
        Geocentric GPS time; subtracted from ``t_det`` in prime space and its
        GMST rotates the ``detector-center-time`` delay into the Earth frame.
    vertex : array_like, optional
        Earth-fixed detector position (metres) for the ``detector-center-time``
        reparameterisation.  Defaults to :data:`ET_EMR_VERTEX`; pass the value
        from :func:`detector_vertex` for a different geometry.
    phase_coordinates : {"polarisation-phase", "arg-alpha-beta", "independent"}, optional
        ``"polarisation-phase"`` (default): the single ``delta_phase`` coordinate
        described above, ``psi`` carried separately (``angle-pi`` /
        ``SingleAngle``).  ``"arg-alpha-beta"``: replace **both** ``psi`` and
        ``phase`` with the two circular-polarisation phases ``arg_alpha =
        (phase - psi)`` and ``arg_beta = (phase + psi)``
        (:class:`~nessai_gw.reparameterisations.phase.ArgAlphaBetaReparameterisation`),
        which put the likelihood ridge on a flow axis.  ``"independent"``:
        ``psi`` and ``phase`` each on their own ``single-angle`` axis, no
        mixing at all -- the right choice when a branch's discrete structure
        sits entirely on one of the two (e.g. the ET-Delta plateau branch,
        where ``phase`` is cleanly bimodal and ``psi`` is a plain, single-
        valued spread; see :mod:`nessai_gw._polarisation_branch`'s module
        docstring), so mixing them the way ``arg-alpha-beta`` does only smears
        that bimodality diagonally across both flow axes instead of confining
        it to one.  ``"independent"`` only works with ``prime_space=False``
        (plain ``phase`` is not group-invariant the simple closed-form way
        ``delta_phase`` is built to be, so :class:`PrimeSpaceTriangularGroupAction`
        has no fast-path support for it -- passing it with ``prime_space=True``
        fails loudly, "prime space is missing ... delta_phase", rather than
        silently doing the wrong thing).  Must match the ``phase_coordinates``
        passed to :func:`make_triangular_group_flow_proposal`.
    chirp_distance : bool, optional
        Reparameterise ``luminosity_distance`` as the Roulet et al. chirp
        distance instead of the default ``distance`` reparameterisation.
        Default ``False``.
    chirp_distance_plane_normal : array_like, optional
        Detector-plane normal for the antenna response used to pick the
        reference detector and evaluate ``R_k0``.  Defaults to
        :data:`ET_EMR_PLANE_NORMAL`.
    chirp_distance_azimuth_offset : float, optional
        In-plane rotation (rad), matching the group action's
        ``azimuth_offset``.  ``cos iota*``-type quantities built from ``R_k``
        do not depend on it in the way the group action itself does, but it
        is accepted so the two can be configured identically.  Default 0.
    chirp_distance_k0 : int, optional
        The reference detector index directly. Exactly one of ``chirp_distance_k0``
        / ``chirp_distance_fiducial`` must be given when ``chirp_distance`` is set.
    chirp_distance_fiducial : mapping, optional
        ``ra``, ``dec``, ``psi``, ``theta_jn`` of a reference signal (typically
        the injection or the maximum-likelihood point), used to pick
        ``k0 = argmax_k |R_k|`` once at construction.

    Returns
    -------
    dict
        A ``reparameterisations`` mapping for ``bilby.run_sampler`` / nessai.
    """
    if vertex is None:
        vertex = ET_EMR_VERTEX
    if chirp_distance and chirp_distance_k0 is None and chirp_distance_fiducial is None:
        raise ValueError(
            "chirp_distance requires either chirp_distance_k0 or "
            "chirp_distance_fiducial."
        )
    if phase_coordinates not in ("polarisation-phase", "arg-alpha-beta", "independent"):
        raise ValueError(
            "phase_coordinates must be 'polarisation-phase', 'arg-alpha-beta' "
            f"or 'independent'; got {phase_coordinates!r}"
        )

    # ``polarisation-phase`` reads x-space ``psi`` and ``theta_jn`` on its
    # inverse, and ``detector-center-time`` reads x-space ``ra`` / ``dec``, so
    # ``CombinedReparameterisation.check_order`` -- which walks the
    # reparameterisations in reverse -- needs the ``phase`` and ``geocent_time``
    # entries to sort *ahead of* the coordinates they consume on the inverse.
    # The sorter only orders by forward-input arity and keeps insertion order on
    # ties (all are arity 1) and ignores inverse inputs entirely, so we emit
    # ``phase`` / ``geocent_time`` first here.  ``psi`` (``angle-pi``) and the
    # sky ``AnglePair`` are added later by ``add_default_reparameterisations``
    # and so are always behind these.
    # ``check_order`` walks the list in reverse for the inverse pass, so a
    # reparameterisation must sort *ahead of* everything it consumes there.
    # ``polarisation-phase`` reads ``psi`` and ``theta_jn``;
    # ``detector-center-time`` and ``polarisation-ellipse`` read ``ra`` / ``dec``
    # -- and ``polarisation-ellipse`` supplies the ``theta_jn`` that
    # ``polarisation-phase`` needs, so it has to sit between the two.
    _rank = {"phase": 0, "geocent_time": 0}
    if polarisation_ellipse is not None:
        _rank["geocent_time"] = 1
        _rank["theta_jn"] = 1
    if chirp_distance:
        # Depends on chirp_mass, theta_jn, ra, dec and psi on its inverse --
        # all either default-added (after every explicit entry here) or, for
        # theta_jn, itself explicit at rank <= 1 above -- so rank it ahead of
        # everything, including phase/geocent_time (no dependency either way).
        _rank["luminosity_distance"] = -1
    ordered_names = sorted(
        sampling_parameters, key=lambda n: _rank.get(n, 2)
    )
    reps = {}
    for name in ordered_names:
        if name == "luminosity_distance" and chirp_distance:
            reps[name] = {
                "reparameterisation": "chirp-distance",
                "plane_normal": (
                    ET_EMR_PLANE_NORMAL if chirp_distance_plane_normal is None
                    else chirp_distance_plane_normal
                ),
                "reference_time": float(reference_time),
                "azimuth_offset": float(chirp_distance_azimuth_offset),
                "k0": chirp_distance_k0,
                "fiducial": chirp_distance_fiducial,
            }
        elif name in ("chi_1", "chi_2"):
            reps[name] = {"reparameterisation": "aligned-spin"}
        elif name in ("lambda_1", "lambda_2"):
            reps[name] = {
                "reparameterisation": "logit",
                "update_bounds": False,
            }
        elif name == "theta_jn":
            if polarisation_ellipse is not None:
                # The sky position *forces* the inclination (the continuous
                # frozen-limit degeneracy); sample the residual about it.  Still
                # odd under the plane reflection and invariant under the quarter
                # turn, so the group action on the coordinate is unchanged.
                # ``ra`` / ``dec`` (sky-ra-dec) are prerequisites.
                reps[name] = {
                    "reparameterisation": "polarisation-ellipse",
                    "ellipse": polarisation_ellipse,
                    "coordinate": polarisation_ellipse_coordinate,
                    "scale": float(polarisation_ellipse_scale),
                    "adaptive_width": bool(
                        polarisation_ellipse_adaptive_width
                    ),
                }
            else:
                reps[name] = {
                    "reparameterisation": "angle-sine",
                    "update_bounds": False,
                }
        elif name == "geocent_time":
            # t_det = geocent_time + delay(ra, dec): the invariant
            # detector-centre arrival time.  ``ra`` / ``dec`` (sky-ra-dec) are
            # prerequisites.
            reps[name] = {
                "reparameterisation": "detector-center-time",
                "vertex": [float(v) for v in np.asarray(vertex)],
                "reference_time": float(reference_time),
                "scale": _GEOCENT_SCALE,
            }
        elif name == "phase":
            if phase_coordinates == "arg-alpha-beta":
                # arg_alpha = (phase - psi), arg_beta = (phase + psi): both
                # circular-polarisation phases on the flow axes.  Keyed by the
                # reparameterisation name (not "phase") with an explicit
                # ``parameters`` list, which both nessai 0.15.x and 0.16.x
                # thread through verbatim -- keying by "phase" would make one of
                # them append "phase" a second time.  Added after the loop.
                continue
            elif phase_coordinates == "independent":
                # phase on its own single-angle axis, psi left to the default
                # psi_single handling -- no mixing at all.  Only valid with
                # prime_space=False; see this function's docstring.
                reps[name] = {"reparameterisation": "single-angle", "scale": 2.0}
            else:
                # delta_phase = phase + sign(cos theta_jn) * psi
                # (polarisation-phase): makes the likelihood-constrained
                # polarisation/phase combination an explicit flow axis.  ``psi``
                # (angle-pi) and ``theta_jn`` (angle-sine) are prerequisites.
                reps[name] = {"reparameterisation": "polarisation-phase"}

    if phase_coordinates == "arg-alpha-beta" and "phase" in sampling_parameters:
        reps["arg-alpha-beta"] = {"parameters": ["psi", "phase"]}
    return reps


#: Dummy prior bounds for the throwaway reparameterisation build in
#: :func:`_prime_parameter_names`.  Values are irrelevant; each just has to be a
#: finite range valid for that parameter's reparameterisation.
_DUMMY_PRIOR_BOUNDS = {
    "ra": (0.0, _TWO_PI),
    "dec": (-np.pi / 2, np.pi / 2),
    "theta_jn": (0.0, np.pi),
    "iota": (0.0, np.pi),
    "tilt_1": (0.0, np.pi),
    "tilt_2": (0.0, np.pi),
    "psi": (0.0, np.pi),
    # ``phase`` bounds also serve the derived ``delta_phase`` coordinate
    # (``polarisation-phase``), which needs no entry of its own.
    "phase": (0.0, _TWO_PI),
    "phi_12": (0.0, _TWO_PI),
    "phi_jl": (0.0, _TWO_PI),
    "a_1": (0.0, 0.99),
    "a_2": (0.0, 0.99),
    "chi_1": (-0.99, 0.99),
    "chi_2": (-0.99, 0.99),
    "luminosity_distance": (10.0, 5000.0),
    "chirp_mass": (1.0, 2.0),
    "mass_ratio": (0.125, 1.0),
    "mass_1": (1.0, 3.0),
    "mass_2": (1.0, 3.0),
    "lambda_1": (0.0, 2500.0),
    "lambda_2": (0.0, 2500.0),
}


def _prime_parameter_names(
    sampling_parameters, reference_time, vertex=None, sky_2d=False,
    psi_single=False, phase_coordinates="polarisation-phase",
    polarisation_ellipse=None, polarisation_ellipse_scale=1.0,
    polarisation_ellipse_coordinate="angle",
    polarisation_ellipse_adaptive_width=False,
    chirp_distance=False,
    chirp_distance_plane_normal=None,
    chirp_distance_azimuth_offset=0.0,
    chirp_distance_k0=None,
    chirp_distance_fiducial=None,
):
    """Prime-parameter names *and order* nessai produces for this wiring.

    Computed by configuring a throwaway
    :class:`nessai_gw.proposals.GWFlowProposal` with the same
    reparameterisation dict / fallback the real proposal uses and reading back
    ``prime_parameters``.  The order matters: the group-mixture wrapper builds
    its base-flow ``point_dict`` from ``param_names`` before
    :meth:`TriangularGroupFlowProposal.initialise` re-binds to the live
    ``prime_parameters``.

    Falls back to a name-order heuristic (right count, order not guaranteed) if
    the throwaway build fails.
    """
    names = list(sampling_parameters)

    try:
        from nessai.model import Model

        from .proposals import GWFlowProposal

        bounds = {
            name: np.asarray(
                _DUMMY_PRIOR_BOUNDS.get(name, (0.0, 1.0)), dtype=float
            )
            for name in names
        }

        class _StubModel(Model):
            def __init__(self):
                self.names = list(names)
                self.bounds = bounds

            def log_prior(self, x):
                return np.zeros(len(np.atleast_1d(x)))

            def log_likelihood(self, x):
                return np.zeros(len(np.atleast_1d(x)))

        probe = GWFlowProposal(
            _StubModel(),
            poolsize=100,
            reparameterisations=triangular_group_reparameterisations(
                names, reference_time, vertex=vertex,
                phase_coordinates=phase_coordinates,
                polarisation_ellipse=polarisation_ellipse,
                polarisation_ellipse_scale=polarisation_ellipse_scale,
                polarisation_ellipse_coordinate=polarisation_ellipse_coordinate,
                polarisation_ellipse_adaptive_width=polarisation_ellipse_adaptive_width,
                chirp_distance=chirp_distance,
                chirp_distance_plane_normal=chirp_distance_plane_normal,
                chirp_distance_azimuth_offset=chirp_distance_azimuth_offset,
                chirp_distance_k0=chirp_distance_k0,
                chirp_distance_fiducial=chirp_distance_fiducial,
            ),
            fallback_reparameterisation="zscore",
        )
        probe.set_rescaling()
        prime = list(probe.prime_parameters)
        if prime:
            if sky_2d:
                # The probe builds the 3-coordinate ``sky-ra-dec`` AnglePair
                # (it has no knowledge of the group proposal's EqualAreaSky
                # override); swap the triple for the 2-coordinate names in
                # place so the pre-bind placeholder has the right count/order.
                prime = _swap_sky_triple_for_pair(prime)
            if (
                phase_coordinates != "arg-alpha-beta"
                and psi_single
                and "psi_x" in prime
                and "psi_y" in prime
            ):
                i = prime.index("psi_x")
                prime = prime[:i] + ["psi_prime"] + [
                    n for n in prime[i:] if n not in ("psi_x", "psi_y")
                ]
            return prime
    except Exception as exc:  # pragma: no cover - defensive
        import warnings

        warnings.warn(
            "Could not probe nessai for the real prime-parameter order "
            f"({exc!r}); falling back to a name-order heuristic. Buffers are "
            "re-bound at initialise, so only the pre-bind placeholder is "
            "affected.",
            RuntimeWarning,
        )

    out = []
    if "ra" in names and "dec" in names:
        out += ["sky_u", "sky_v"] if sky_2d else [
            "ra_dec_x", "ra_dec_y", "ra_dec_z"
        ]
    for name in names:
        if name in ("ra", "dec"):
            continue
        if name == "phase":
            if phase_coordinates == "arg-alpha-beta":
                # arg-alpha-beta consumes both psi and phase -> emit the pair
                # here and skip psi below.
                out += ["arg_alpha", "arg_beta"]
            else:
                # single ``delta_phase`` polarisation-phase coordinate
                out.append("delta_phase")
        elif name == "psi" and phase_coordinates == "arg-alpha-beta":
            continue  # folded into (arg_alpha, arg_beta)
        elif name == "geocent_time":
            # detector-center-time: single ``t_det`` coordinate (no suffix)
            out.append("t_det")
        elif name in _ANGLE_SCALE:
            out += (
                [f"{name}_prime"]
                if (psi_single and name == "psi")
                else [f"{name}_x", f"{name}_y"]
            )
        elif name == "luminosity_distance" and chirp_distance:
            out.append("chirp_distance")
        else:
            out.append(f"{name}_prime")
    return out


def _swap_sky_triple_for_pair(prime):
    """Replace ``ra_dec_{x,y,z}`` (or ``dec_ra_*``) with ``sky_u, sky_v``."""
    for prefix in ("ra_dec", "dec_ra"):
        trip = [f"{prefix}_{c}" for c in ("x", "y", "z")]
        if all(t in prime for t in trip):
            i = prime.index(trip[0])
            return prime[:i] + ["sky_u", "sky_v"] + [
                n for n in prime[i:] if n not in trip
            ]
    return prime


def recommended_polarisation_offset(psi):
    """Fold ``psi`` to its canonical half and report where it sits.

    For the ``polarisation_offset`` seam (see
    :class:`TriangularDetectorGroupAction`'s docstring) instead of the sky's
    Z4 wedge: with ``polarisation_quarter``, the two candidate ``psi``
    images of any physical point are always exactly ``pi/2`` apart (mod
    ``pi``), so folding ``psi`` to ``[0, pi/2)`` and checking its circular
    concentration there works exactly like the sky case, one dimension down
    (a Z2 rather than a Z4 division of the circle -- but the fold interval is
    the same ``pi/2``, so the formulas match with ``4 psi_f`` in place of
    ``4 lam_f``).

    Returns a dict with ``concentration``, ``circ_mean_lambda`` (the folded
    ``psi``'s circular mean), ``recommended_azimuth_offset`` (the recommended
    ``polarisation_offset``), ``fraction_near_seam`` and ``n``.

    Parameters
    ----------
    psi : array_like
        Live-point ``psi`` values (radians) -- from a canonically-folded,
        reasonably localised run.  Pass a single branch's own ``psi`` (e.g.
        via :func:`nessai_gw._polarisation_branch.diagonal_split_mask`) if
        splitting into branches; the two branches can end up wanting
        different offsets, exactly as they wanted different phase bases (see
        :func:`nessai_gw._polarisation_branch.fit_phase_rotation`).
    """
    psi = np.asarray(psi, dtype=float)
    psi_f = np.mod(psi, 0.5 * np.pi)
    z = np.mean(np.exp(4j * psi_f))
    circ_mean = np.mod(np.angle(z) / 4.0, 0.5 * np.pi)
    return {
        "concentration": float(np.abs(z)),
        "circ_mean_lambda": float(circ_mean),
        "recommended_azimuth_offset": float(
            np.mod(circ_mean - 0.25 * np.pi, 0.5 * np.pi)
        ),
        "fraction_near_seam": float(
            np.mean((psi_f < 0.15) | (psi_f > 0.5 * np.pi - 0.15))
        ),
        "n": int(psi.size),
    }


def _select_flow_model_factory(
    n_clusters_max,
    flow_model_factory=None,
    cluster_method="gmm",
    cluster_max_overlap=0.05,
    cluster_min_size=200,
    cluster_bg_weight=0.0,
    cluster_k_grow_patience=2,
    cluster_centroid_ema=None,
):
    """The ``make_*_group_mixture_flow`` callable a group proposal factory uses:
    nessai's single-flow factory, its clustered one (``n_clusters_max > 1``), or
    a user ``flow_model_factory`` (only with ``n_clusters_max > 1``)."""
    from nessai.flowmodel.group_mixture import make_group_mixture_flow

    if int(n_clusters_max) > 1 and flow_model_factory is not None:
        _make_flow_model = flow_model_factory
    elif int(n_clusters_max) > 1:
        try:
            from nessai.flowmodel.group_mixture import (
                make_clustered_group_mixture_flow,
            )
        except ImportError as exc:  # pragma: no cover
            raise RuntimeError(
                "n_clusters_max > 1 requires a version of nessai whose "
                "nessai.flowmodel.group_mixture ships "
                "make_clustered_group_mixture_flow."
            ) from exc

        def _make_flow_model(**gm):
            extra = {}
            _sig = inspect.signature(make_clustered_group_mixture_flow)
            if "k_grow_patience" in _sig.parameters:
                extra["k_grow_patience"] = int(cluster_k_grow_patience)
            if "centroid_ema" in _sig.parameters:
                extra["centroid_ema"] = (
                    None if cluster_centroid_ema is None
                    else float(cluster_centroid_ema)
                )
            return make_clustered_group_mixture_flow(
                n_clusters_max=int(n_clusters_max),
                cluster_method=cluster_method,
                max_cluster_overlap=float(cluster_max_overlap),
                min_cluster_size=int(cluster_min_size),
                bg_weight=float(cluster_bg_weight),
                **extra,
                **gm,
            )
    else:
        _make_flow_model = make_group_mixture_flow
    return _make_flow_model


def _make_group_proposal_class(
    class_name,
    flow_model_cls,
    action,
    sky_rotation,
    sky_2d,
    psi_single,
    phase_coordinates,
    sky_radial_sigma=0.15,
):
    """``FlowProposal`` subclass for a nessai-gw group-mixture flow.

    Shared by :func:`make_triangular_group_flow_proposal` and
    :func:`nessai_gw.network_group.make_network_group_flow_proposal`: the sky
    is carried in the frame ``sky_rotation`` (equatorial -> flow frame, GMST
    folded in) by :class:`~nessai_gw.reparameterisations.sky.EqualAreaSky`
    (``sky_2d``) or :class:`~nessai_gw.reparameterisations.sky.RotatedAnglePair`,
    ``psi`` optionally by a single ``psi_prime`` coordinate, and a prime-space
    ``action`` (``None`` on the physical-space path) is re-bound to nessai's
    actual prime-parameter order after every (re-)initialisation.  The class is
    published at module scope as ``class_name`` so checkpoints unpickle.
    """
    from nessai.flowmodel.group_mixture import GroupFlowProposalMixin
    from nessai.proposal import FlowProposal

    from .proposals import GWReparamMixin

    class _GroupFlowProposal(
        GWReparamMixin, GroupFlowProposalMixin, FlowProposal
    ):
        """``FlowProposal`` wired for a nessai-gw group-mixture flow with the
        nessai-gw GW reparameterisations."""

        _FlowModelClass = flow_model_cls

        def add_default_reparameterisations(self):
            # Sky: carried in the ``sky_rotation`` frame (for a triangle, the
            # detector frame, so the group's fundamental domain is
            # axis-aligned rather than an oblique equatorial wedge).
            rep = self._reparameterisation
            model_names = set(self.model.names)
            if (
                phase_coordinates != "arg-alpha-beta"
                and psi_single
                and "psi" in model_names
                and "psi" not in set(rep.parameters)
            ):
                # Single ``psi_prime`` coordinate instead of the angle-pi
                # Cartesian pair + chi(2) radius (the bare psi is only weakly
                # constrained; the pair's free radius gives an origin cusp).
                from .reparameterisations.phase import (
                    SingleAngleReparameterisation,
                )

                rep.add_reparameterisation(
                    SingleAngleReparameterisation(
                        parameters=["psi"],
                        prior_bounds={"psi": self.model.bounds["psi"]},
                        scale=2.0,
                    )
                )
            if {"ra", "dec"} <= model_names and not (
                {"ra", "dec"} & set(rep.parameters)
            ):
                sky_bounds = {
                    k: self.model.bounds[k] for k in ("ra", "dec")
                }
                if sky_2d:
                    from .reparameterisations.sky import EqualAreaSky

                    rep.add_reparameterisation(
                        EqualAreaSky(
                            parameters=["ra", "dec"],
                            prior_bounds=sky_bounds,
                            rotation=sky_rotation,
                            rng=self.rng,
                        )
                    )
                else:
                    from .reparameterisations.sky import RotatedAnglePair

                    rep.add_reparameterisation(
                        RotatedAnglePair(
                            parameters=["ra", "dec"],
                            prior_bounds=sky_bounds,
                            convention="ra-dec",
                            rotation=sky_rotation,
                            radial_sigma=sky_radial_sigma,
                            rng=self.rng,
                        )
                    )
            super().add_default_reparameterisations()

        def _realign_prime_space_action(self):
            """Realign the prime-space action and model to nessai's actual
            prime parameter order (do not assume the reparameterisation-dict
            order, nor the throwaway-probe order ``_prime_parameter_names``
            predicted when ``flow_model_cls`` was built -- see that
            function's docstring). ``get_model()`` (called both by
            ``initialise()`` and, on every ``--reset-flow`` trigger, by
            ``FlowModel.reset_model()``) falls back to that predicted order
            via the ``param_names`` *class* attribute, so this must be
            re-applied after a reset too, not just once at startup -- a
            reset that skipped it silently reverted every model to the
            (possibly wrong) predicted order, scrambling which physical
            quantity landed in which prime-vector column.
            """
            if action is None:
                return
            model = getattr(self.flow, "model", None)
            prime = list(getattr(self, "prime_parameters", []) or [])
            if model is not None and prime:
                action.bind(prime)
                if hasattr(model, "set_param_names"):
                    model.set_param_names(prime)
                else:
                    model.param_names = prime

        def initialise(self, *args, **kwargs):
            super().initialise(*args, **kwargs)
            self._realign_prime_space_action()

        def reset_model_weights(self, **kwargs):
            super().reset_model_weights(**kwargs)
            self._realign_prime_space_action()

    # nessai checkpoints the sampler (hence the proposal *instance*) with
    # ``pickle``, which resolves an instance's class by ``module.__qualname__``.
    # Publish this otherwise-local class at module scope under a stable name.
    _GroupFlowProposal.__name__ = class_name
    _GroupFlowProposal.__module__ = __name__
    _GroupFlowProposal.__qualname__ = class_name
    globals()[class_name] = _GroupFlowProposal
    return _GroupFlowProposal


def make_triangular_group_flow_proposal(
    sampling_parameters,
    reference_time,
    plane_normal,
    vertex,
    prime_space=True,
    phase_reflection=False,
    azimuth_offset=0.0,
    boundary_reflection=False,
    sky_radial_sigma=0.15,
    gaussianise_sky="auto",
    sky_2d="auto",
    sky_pullback=None,
    psi_single=True,
    polarisation_quarter=True,
    polarisation_offset=0.0,
    phase_coordinates="polarisation-phase",
    n_clusters_max=1,
    cluster_method="gmm",
    cluster_max_overlap=0.05,
    cluster_min_size=200,
    cluster_bg_weight=0.0,
    cluster_k_grow_patience=2,
    cluster_centroid_ema=None,
    flow_model_factory=None,
    polarisation_ellipse=None,
    polarisation_ellipse_scale=1.0,
    polarisation_ellipse_coordinate="angle",
    polarisation_ellipse_adaptive_width=False,
    phase_recanon=False,
    adaptive_domain=False,
    chirp_distance=False,
    chirp_distance_k0=None,
    chirp_distance_fiducial=None,
):
    """Build a ``FlowProposal`` subclass wired for the triangular-detector group mixture.

    ``flow_model_factory`` (optional): a callable used *instead of*
    :func:`nessai.flowmodel.group_mixture.make_clustered_group_mixture_flow`
    when ``n_clusters_max > 1``.  It is called with the group keyword arguments
    (``group_action_fn`` / ``prime_space_action`` / ``param_names`` /
    ``group_size`` / ``mode_factor_sizes`` / ``canonical_transform`` / ...) and
    must return a ``FlowModel`` subclass.  Use it to plug in a bespoke
    clustering strategy (e.g. a fixed rule-based split); pre-bind its own
    configuration with :func:`functools.partial`.  The ``cluster_*`` arguments
    above are then ignored.

    The returned class combines :class:`nessai_gw.proposals.GWReparamMixin`
    (GW reparameterisations by parameter name),
    :class:`nessai.flowmodel.group_mixture.GroupFlowProposalMixin` (group-mixture
    wiring) and :class:`nessai.proposal.FlowProposal`, with
    :class:`TriangularDetectorGroupAction` as the group action.  Pass it as
    ``flow_proposal_class`` to ``bilby.run_sampler(sampler="nessai", ...)``
    together with :func:`triangular_group_reparameterisations`.

    Parameters
    ----------
    sampling_parameters : list of str
        Every parameter nessai samples, in order.  Must contain ``ra``, ``dec``,
        ``theta_jn``, ``psi``, ``phase`` and ``geocent_time``.
    reference_time : float
        Geocentric GPS time of the event.
    plane_normal : array_like
        Earth-fixed unit normal to the detector plane.
    vertex : array_like
        Geocentric detector position (metres).
    prime_space : bool, optional
        If ``True`` (default) run the action in the flow's prime space via
        :class:`PrimeSpaceTriangularGroupAction` (exact unit Jacobian, no
        per-call numpy round-trip).  If ``False`` run it in physical coordinates
        and let nessai's ``GroupFlowProposalMixin`` bridge to prime space with a
        ``ReparamBridge``.
    phase_reflection : bool, optional
        Fold in the extra ``phase -> phase + pi`` (2, 2)-mode degeneracy
        (16-element group).  See :class:`TriangularDetectorGroupAction`.
    azimuth_offset : float, optional
        In-plane rotation (rad) of the detector frame about the plane normal,
        shifting the Z4 fundamental-domain seams by a fixed amount (kept for
        reproducing older runs; ``adaptive_domain`` moves the seams per
        expert from the data instead).  Default ``0.0``.
    boundary_reflection : bool, optional
        Only on the prime-space path.  Symmetrise the base flow across the
        ``ra_dec_{x,y,z} = 0`` octant faces so it need not model the wall
        cliffs (see ``reflect_parameters`` in
        :func:`nessai.flowmodel.group_mixture.make_group_mixture_flow`).
        Default ``False``.
    sky_radial_sigma : float or None, optional
        Width of the auxiliary sky radial coordinate (see
        :class:`~nessai_gw.reparameterisations.sky.RotatedAnglePair`).  The
        default (``0.15``) confines the sky prime points to a thin unit shell
        so the base flow never has to taper a cone into the ``r = 0``
        coordinate singularity; ``None`` restores ``AnglePair``'s ``chi(3)``.
    gaussianise_sky : bool or "auto", optional
        Only on the prime-space path.  Install :class:`SkyOctantGaussianiser`
        as the group-mixture ``canonical_transform``: the base flow then sees
        the canonical sky octant mapped (cylindrical equal-area + probit) to
        two independent standard normals plus the pass-through radius, instead
        of the uniform-on-sphere octant with its hard prior edge.  Supersedes
        ``boundary_reflection`` for the sky (the octant walls move to
        ``+/-inf``).  Default ``"auto"`` -- on whenever ``prime_space`` is
        ``True``.  Pass ``False`` to opt out, or an explicit ``True`` with
        ``prime_space=False`` to get an error rather than a silent no-op.
    sky_2d : bool or "auto", optional
        Drop the auxiliary sky radial coordinate and carry the sky as the two
        equal-area coordinates ``(sky_u, sky_v)`` (see
        :class:`~nessai_gw.reparameterisations.sky.EqualAreaSky` +
        :class:`SkyOctantProbit`).  Default ``"auto"`` -- on whenever
        ``prime_space`` and ``gaussianise_sky`` are both active (the machinery
        it needs), off otherwise.  Requires the prime-space path.
    sky_pullback : array_like or None, optional
        ``(Nu, Nv)`` grid of the analytic prior-pullback sky density ``q``,
        **folded to the fundamental sub-square** ``sky_u in [0, 1/4)`` x
        ``sky_v in [0, 1/2)`` (see
        :class:`SkyOctantPullback` and :func:`folded_sky_pullback_grid`).  When
        given, :class:`SkyOctantPullback` replaces :class:`SkyOctantProbit` as
        the group-mixture ``canonical_transform``: the base flow then sees the
        folded sky posterior mapped (exact 2-D PIT of ``q``) to ~two standard
        normals rather than the uniform sub-square, so it need only learn the
        small residual.  Requires ``sky_2d``.  Default ``None`` (uniform PIT).
    psi_single : bool, optional
        Carry ``psi`` as a single ``psi_prime`` coordinate
        (:class:`~nessai_gw.reparameterisations.phase.SingleAngleReparameterisation`)
        instead of the ``angle-pi`` Cartesian pair + ``chi(2)`` radius.  The
        free radius of the pair turns a well-structured ``psi`` into a
        leptokurtic origin cusp; the single coordinate is cleaner (measured
        ~1.4 nat lower non-Gaussianity on a v16 ET-Delta fold).  Default
        ``True``.
    polarisation_quarter : bool, optional
        Promote the phase sector from ``Z2`` to ``Z4`` by folding the
        ``{psi -> psi + pi/2, phase -> phase - pi/2}`` polarisation/phase
        quarter turn into the group (32 elements; forces
        ``phase_reflection``).  This makes ``psi_prime`` unimodal in the base
        frame -- the ``{psi -> psi + pi/2}`` degeneracy is otherwise left for
        the base flow to model as a second mode.  Default ``True``.
    polarisation_offset : float, optional
        Only used with ``polarisation_quarter``.  See
        :class:`TriangularDetectorGroupAction`'s docstring -- the ``psi``
        seam the canonical-point test uses (``psi mod pi < pi/2``) is
        arbitrary, exactly like the sky's Z4 wedge boundary
        ``azimuth_offset`` exists to move; if the run's actual ``psi``
        posterior straddles it, points fold to different ``phase_step``
        images and the ``(psi, phase)`` corner looks like two offset ridges
        rather than one.  Prefer ``adaptive_domain``.  Default ``0.0``.
    phase_coordinates : {"polarisation-phase", "arg-alpha-beta", "independent"}, optional
        ``"polarisation-phase"`` (default): ``delta_phase = phase + sign(cos
        theta_jn) psi`` + a separate ``psi`` coordinate.  ``"arg-alpha-beta"``:
        carry both circular-polarisation phases ``arg_alpha = (phase - psi)``
        and ``arg_beta = (phase + psi)`` as flow axes instead (folds out ``psi``
        and ``delta_phase``); on the octomodal ET BNS fold this cut base-flow
        NLL by ~1 nat over the equivalently-grouped ``delta_phase`` block.  The
        polarisation-quarter Z4 still acts on ``(arg_alpha, arg_beta)`` and is
        kept as a weight-learned group factor -- keep ``polarisation_quarter``
        as you would otherwise.  ``"independent"``: no mixing at all, ``psi``
        and ``phase`` each on their own axis -- for a branch whose discrete
        structure sits entirely on ``phase`` (mixing in ``psi`` only smears it
        diagonally across two axes instead of confining it to one; see
        :mod:`nessai_gw._polarisation_branch`).  Requires
        ``prime_space=False`` -- raises during proposal construction otherwise
        (:class:`PrimeSpaceTriangularGroupAction` has no fast-path support for
        a bare, non-group-invariant ``phase``).  Must match the
        ``phase_coordinates`` passed to
        :func:`triangular_group_reparameterisations`.
    n_clusters_max : int
        If ``> 1``, use a *clustered* base flow: up to ``n_clusters_max``
        independent group-mixture experts, one per data cluster (found each
        training round by GMM + BIC, ``k`` in ``[1, n_clusters_max]``), each
        with its own per-branch canonical standardisation and latent ball.
        ``k`` collapses to 1 -- byte identical to the single-flow behaviour --
        whenever the data is not decisively multi-modal.  Default ``1`` (off).
    cluster_method : {"gmm", "kmeans"}
        Clustering algorithm on the standardised folded base frame.
    cluster_max_overlap : float
        A ``k``-way split is accepted only if at most this fraction of points
        are ambiguous between clusters (GMM responsibility < 0.8).  Smaller =
        more conservative; ``k`` collapses to 1 when no split is clean.
    cluster_min_size : int
        Smallest allowed cluster (a split producing a smaller cluster is
        rejected).
    cluster_bg_weight : float
        Weight of an always-on background expert (a group-mixture flow trained
        on all live points, blended into the mixture at ``k >= 2`` so the
        density never craters where the per-cluster experts leave off).  ``0``
        (default) -> no background expert.
    polarisation_ellipse : nessai_gw._ellipse.PolarisationEllipse, optional
        Sample the inclination *relative to the value the sky position forces*
        (the ``polarisation-ellipse`` reparameterisation) instead of with
        ``angle-sine``.  ``G_8`` is only a discrete subgroup of a degeneracy
        that is continuous over the whole sky: fixing the sky fixes the
        polarisation ellipse, so the folded posterior is still a curved sheet
        ``cos theta_jn ~ cos iota*(n)`` and the ``theta_jn`` prime coordinate
        comes out flat-topped or bimodal.  Subtracting the lock makes it a
        single unimodal residual.  Measured on the ET-Delta v70 nested samples,
        through the multimodal middle of the run (``-lnX`` 30-50) this takes
        the folded ``theta_jn_prime`` excess kurtosis from about ``-1.2`` to
        about ``0`` and the nearest-neighbour ``KL(p || Gaussian)`` of the
        folded 11-dimensional live-point set down by 0.04-0.43 nats out of
        1.6-4.6.  Needs a fiducial signal (typically the maximum-likelihood
        point), so it is opt-in; ``None`` (the default) keeps ``angle-sine``.
    polarisation_ellipse_coordinate : {"angle", "cos"}, optional
        Whether the residual is taken in ``theta_jn`` or in ``cos theta_jn``;
        see :class:`~nessai_gw.reparameterisations.PolarisationEllipseReparameterisation`.
        ``"angle"`` (the default) keeps ``angle-sine``'s constant Jacobian and
        its smooth prime-space prior, which matters early in a run before the
        likelihood has locked the sheet.
    polarisation_ellipse_scale : float, optional
        Prime-space scale of that coordinate (default 1).
    polarisation_ellipse_adaptive_width : bool, optional
        Pass ``adaptive_width=True`` to the ``polarisation-ellipse``
        reparameterisation: the residual is divided by a fitted sky-dependent
        width so the flow coordinate is homoskedastic (the plain residual fans
        out towards the face-on points).  Default ``False``.
    phase_recanon : bool, optional
        Give every group-mixture expert a :class:`PhaseQuarterRecanonicaliser`
        ``base_reparam``: each expert independently switches the polarisation
        quarter-turn fundamental domain from ``psi in [0, pi/2)`` to
        ``phase mod pi/2`` when its points pin the raw phase rather than
        ``delta_phase``.  Needs the prime-space path, ``psi_single``,
        ``polarisation_quarter``, ``phase_coordinates='polarisation-phase'``,
        no ``polarisation_ellipse`` and no boundary reflection.  Default
        ``False``.  With ``adaptive_domain`` this instead allows the
        ``"phase"`` family of :class:`AdaptiveFundamentalDomain`.
    adaptive_domain : bool, optional
        Give every group-mixture expert an :class:`AdaptiveFundamentalDomain`
        ``base_reparam``: each expert moves the sky, ``psi`` and
        ``delta_phase`` fold seams off its own posterior mass every round
        (and, with ``phase_recanon``, may fold the quarter turn on the phase).
        Same requirements as ``phase_recanon``, plus ``sky_2d``.  Default
        ``False``.
    """
    try:
        from nessai.flowmodel.group_mixture import make_group_mixture_flow
    except ImportError as exc:  # pragma: no cover - depends on nessai version
        raise RuntimeError(
            "make_triangular_group_flow_proposal requires a version of nessai "
            "that ships nessai.flowmodel.group_mixture (GroupFlowProposalMixin, "
            "make_group_mixture_flow)."
        ) from exc

    _make_flow_model = _select_flow_model_factory(
        n_clusters_max,
        flow_model_factory,
        cluster_method=cluster_method,
        cluster_max_overlap=cluster_max_overlap,
        cluster_min_size=cluster_min_size,
        cluster_bg_weight=cluster_bg_weight,
        cluster_k_grow_patience=cluster_k_grow_patience,
        cluster_centroid_ema=cluster_centroid_ema,
    )

    if gaussianise_sky == "auto":
        gaussianise_sky = bool(prime_space)
    elif gaussianise_sky and not prime_space:
        raise RuntimeError(
            "gaussianise_sky is only supported on the prime-space path "
            "(prime_space=True)."
        )
    if sky_2d == "auto":
        # 2-D equal-area sky (no auxiliary radial coord) whenever the
        # prime-space + gaussianise-sky machinery it needs is available.
        sky_2d = bool(prime_space) and bool(gaussianise_sky)
    if sky_2d and not prime_space:
        raise RuntimeError("sky_2d is only supported on the prime-space path.")
    if sky_2d and not gaussianise_sky:
        raise RuntimeError(
            "sky_2d needs gaussianise_sky (the SkyOctantProbit canonical "
            "transform turns the folded equal-area sub-square into N(0, 1))."
        )
    if phase_coordinates not in ("polarisation-phase", "arg-alpha-beta", "independent"):
        raise ValueError(
            "phase_coordinates must be 'polarisation-phase', 'arg-alpha-beta' "
            f"or 'independent'; got {phase_coordinates!r}"
        )
    if phase_coordinates == "independent" and prime_space:
        raise RuntimeError(
            "phase_coordinates='independent' needs prime_space=False -- plain "
            "phase is not group-invariant the closed-form way delta_phase is, "
            "so PrimeSpaceTriangularGroupAction has no fast-path support for "
            "it."
        )
    if sky_pullback is not None:
        if not sky_2d:
            raise RuntimeError(
                "sky_pullback needs sky_2d (it replaces the SkyOctantProbit "
                "PIT of the (sky_u, sky_v) sub-square)."
            )
        sky_pullback = np.asarray(sky_pullback, dtype=float)
        if sky_pullback.ndim != 2:
            raise ValueError(
                f"sky_pullback must be a 2-D grid; got shape {sky_pullback.shape}"
            )

    names = list(sampling_parameters)
    missing = sorted(
        {"ra", "dec", "theta_jn", "psi", "phase", "geocent_time"} - set(names)
    )
    if missing:
        raise RuntimeError(
            f"The sampling space is missing {missing}, which the triangular-detector "
            "group action needs; this proposal only applies to a single-site "
            "triangular-detector run with the standard extrinsic parameters."
        )

    base_action = TriangularDetectorGroupAction(
        reference_time=reference_time,
        plane_normal=plane_normal,
        vertex=vertex,
        phase_reflection=phase_reflection,
        azimuth_offset=azimuth_offset,
        polarisation_quarter=polarisation_quarter,
        polarisation_offset=polarisation_offset,
    )

    if prime_space:
        prime_names = _prime_parameter_names(
            names, reference_time, vertex=vertex, sky_2d=sky_2d,
            psi_single=psi_single, phase_coordinates=phase_coordinates,
            polarisation_ellipse=polarisation_ellipse,
            polarisation_ellipse_scale=polarisation_ellipse_scale,
            polarisation_ellipse_coordinate=polarisation_ellipse_coordinate,
            polarisation_ellipse_adaptive_width=polarisation_ellipse_adaptive_width,
            chirp_distance=chirp_distance,
            chirp_distance_plane_normal=plane_normal,
            chirp_distance_azimuth_offset=azimuth_offset,
            chirp_distance_k0=chirp_distance_k0,
            chirp_distance_fiducial=chirp_distance_fiducial,
        )
        action = PrimeSpaceTriangularGroupAction(
            base_action, prime_names, ellipse=polarisation_ellipse,
            ellipse_scale=polarisation_ellipse_scale,
            ellipse_coordinate=polarisation_ellipse_coordinate,
        )
        gm_kwargs = {}
        import inspect as _inspect

        _gm_params = _inspect.signature(make_group_mixture_flow).parameters
        if "mode_factor_sizes" in _gm_params:
            gm_kwargs["mode_factor_sizes"] = base_action.mode_factor_sizes
        if gaussianise_sky:
            if "canonical_transform" not in _gm_params:
                raise RuntimeError(
                    "gaussianise_sky requires a version of nessai whose "
                    "make_group_mixture_flow accepts `canonical_transform`."
                )
            if not sky_2d:
                gm_kwargs["canonical_transform"] = SkyOctantGaussianiser(
                    prime_names
                )
            elif sky_pullback is not None:
                gm_kwargs["canonical_transform"] = SkyOctantPullback(
                    sky_pullback, prime_names
                )
            else:
                gm_kwargs["canonical_transform"] = SkyOctantProbit(prime_names)
            if boundary_reflection:
                logger.warning(
                    "gaussianise_sky pushes the octant walls to +/-inf; "
                    "ignoring boundary_reflection for the sky coordinates."
                )
                boundary_reflection = False
        if boundary_reflection:
            if "reflect_parameters" not in _gm_params:
                raise RuntimeError(
                    "boundary_reflection requires a version of nessai whose "
                    "make_group_mixture_flow accepts `reflect_parameters`."
                )
            gm_kwargs["reflect_parameters"] = [
                p
                for p in ("ra_dec_x", "ra_dec_y", "ra_dec_z")
                if p in prime_names
            ]
        if phase_recanon or adaptive_domain:
            bad = []
            if adaptive_domain and not sky_2d:
                bad.append("sky_2d=False")
            if not psi_single:
                bad.append("psi_single=False")
            if not polarisation_quarter:
                bad.append("polarisation_quarter=False")
            if phase_coordinates != "polarisation-phase":
                bad.append(f"phase_coordinates={phase_coordinates!r}")
            if polarisation_ellipse is not None:
                bad.append("polarisation_ellipse")
            if boundary_reflection:
                bad.append("boundary_reflection")
            if bad:
                raise RuntimeError(
                    "phase_recanon/adaptive_domain is incompatible with "
                    f"{', '.join(bad)}."
                )
            if "base_reparam_factory" not in _gm_params:
                raise RuntimeError(
                    "phase_recanon/adaptive_domain requires a version of "
                    "nessai whose make_group_mixture_flow accepts "
                    "`base_reparam_factory`."
                )
            import functools as _functools

            if adaptive_domain:
                gm_kwargs["base_reparam_factory"] = _functools.partial(
                    AdaptiveFundamentalDomain, action, list(prime_names),
                    allow_phase_mode=bool(phase_recanon),
                )
            else:
                gm_kwargs["base_reparam_factory"] = _functools.partial(
                    PhaseQuarterRecanonicaliser, list(prime_names)
                )
        flow_model_cls = _make_flow_model(
            group_action_fn=action,  # ignored on the prime-space path
            group_size=base_action.group_size,
            param_names=prime_names,
            prime_space_action=action,
            prime_space_in_domain=action.in_fundamental_domain,
            min_canon_std=_MIN_CANON_STD,
            **gm_kwargs,
        )
    else:
        if phase_recanon or adaptive_domain:
            raise RuntimeError(
                "phase_recanon/adaptive_domain needs the prime-space path."
            )
        action = None
        import inspect as _inspect

        _extra = {}
        if (
            "mode_factor_sizes"
            in _inspect.signature(make_group_mixture_flow).parameters
        ):
            _extra["mode_factor_sizes"] = base_action.mode_factor_sizes
        flow_model_cls = _make_flow_model(
            group_action_fn=base_action,
            group_size=base_action.group_size,
            param_names=base_action.parameters,
            in_fundamental_domain=base_action.in_fundamental_domain,
            min_canon_std=_MIN_CANON_STD,
            **_extra,
        )

    return _make_group_proposal_class(
        "TriangularGroupFlowProposal",
        flow_model_cls,
        action,
        sky_rotation=base_action.sky_frame_rotation,
        sky_2d=sky_2d,
        psi_single=psi_single,
        phase_coordinates=phase_coordinates,
        sky_radial_sigma=sky_radial_sigma,
    )


