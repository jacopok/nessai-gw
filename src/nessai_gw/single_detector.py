"""Discrete symmetry group of a single interferometer (an L, or any opening angle).

A lone interferometer with unit arms ``a``, ``b`` at opening angle ``alpha``
has the detector tensor

    D = (a a - b b) / 2 = (sin(alpha) / 2) (e1 e1 - e2 e2),

with ``e1``, ``e2`` the in-plane bisector of the arms rotated by ``-pi/4`` and
``+pi/4``.  Every opening angle is therefore a right-angled L with *effective
arms* ``e1``, ``e2``, scaled by ``sin(alpha)``: ``alpha`` places the frame (and
sets the amplitude) but does not change the group.  A Cosmic Explorer L
(``alpha = pi/2``) and one channel of a triangular ET (``alpha = pi/3``) share
it.

In the long-wavelength / frozen-Earth limit the response
``D : (F_+ e_+ + F_x e_x)`` is invariant (up to a sign) under every orthogonal
map ``O`` of the detector frame with ``O D O^T = +-D``: the group ``D4h`` of
order 16, generated by

* the quarter turn ``C4`` about the normal (``O D O^T = -D``),
* the reflection ``sigma_h`` through the detector plane (``+D``),
* the reflection ``sigma_v`` through the ``(e1, normal)`` plane (``+D``).

The source direction ``w`` and bilby's polarisation vector ``m`` are mapped by
``O``; a ``-D`` element is compensated by ``psi -> psi + pi/2`` (which flips
the sign of both polarisations, exactly), an improper element (``det O = -1``)
by ``theta_jn -> pi - theta_jn`` (with ``phi_jl -> phi_jl + pi`` for precessing
spins; it flips the handedness of the polarisation
frame, i.e. the sign of ``h_x``; exact for the (2, 2) mode, as for the
triangle's plane reflection).  The group is **not abelian**, so the inverse of
an element comes from its multiplication table.

As on the triangle, the optional polarisation/phase ``Z4``
(``psi -> psi + pi/2, phase -> phase - pi/2``) or its square
(``phase -> phase + pi``) is a second, commuting factor: 32 / 64 elements.
The detector-centre arrival time is invariant under the whole group, and in
the measure-preserving coordinates (``ra``, ``sin_dec``, ``cos_theta_jn``,
``psi``, ``phase``) every element has unit Jacobian.

A lone interferometer also measures a single complex amplitude per mode,
``A = F_+ (1 + cos^2 theta_jn) / 2 - i F_x cos theta_jn``, so at a *fixed*
sky position ``theta_jn -> pi - theta_jn`` with ``psi -> 2 beta - psi``
leaves it unchanged, ``beta`` the polarisation angle at which ``F_x`` vanishes
(the reflection keeps ``F_+`` and flips ``F_x``); with ``phi_jl -> phi_jl +
pi`` for precessing spins, as for the improper elements.  It is exact for the
(2, 2) mode at frozen Earth orientation, commutes with the sky group (which
maps ``D`` to ``+-D`` and so keeps its principal axes) and with the
polarisation/phase steps, and is the optional third factor
(``inclination_reflection``): 64 -> 128 elements.  None of the sky elements
can stand in for it: they all move the sky.

Mode index: ``g = k + 4 r + 8 v`` for the sky element ``C4^k sigma_h^r
sigma_v^v`` (``sigma_v`` applied first), ``phase_step = (mode // 16) % n_phase``
and the inclination reflection ``mode // (16 n_phase)``.
"""

