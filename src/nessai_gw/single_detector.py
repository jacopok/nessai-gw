#: Order of the sky group ``D4h``.
SINGLE_INTERFEROMETER_SKY_GROUP_SIZE = 16


def _sky_group_tables():
    """Matrices, response signs, determinants, product and inverse tables of
    ``D4h`` in the effective-arm frame ``(e1, e2, normal)``."""
    D = np.diag([1.0, -1.0, 0.0])
    sigma_h = np.diag([1.0, 1.0, -1.0])
    sigma_v = np.diag([1.0, -1.0, 1.0])
    mats = []
    for g in range(SINGLE_INTERFEROMETER_SKY_GROUP_SIZE):
        k, r, v = g % 4, (g // 4) % 2, g // 8
        c, s = np.rint(np.cos(0.5 * np.pi * k)), np.rint(np.sin(0.5 * np.pi * k))
        rot = np.array([[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]])
        mats.append(
            rot
            @ np.linalg.matrix_power(sigma_h, r)
            @ np.linalg.matrix_power(sigma_v, v)
        )
    mats = np.array(mats)
    signs = np.array([np.sum(O @ D @ O.T * D) / 2.0 for O in mats])
    assert np.all(np.abs(np.abs(signs) - 1.0) < 1e-12)
    dets = np.rint(np.linalg.det(mats))
    n = len(mats)
    product = np.empty((n, n), dtype=np.int64)
    for i in range(n):
        for j in range(n):
            P = mats[i] @ mats[j]
            product[i, j] = int(
                np.argmin(np.abs(mats - P).reshape(n, -1).sum(-1))
            )
    inverse = np.array([int(np.where(product[i] == 0)[0][0]) for i in range(n)])
    return mats, np.rint(signs), dets, product, inverse


(
    _SKY_MATRICES,
    _SKY_SIGNS,
    _SKY_DETS,
    SKY_PRODUCT_TABLE,
    SKY_INVERSE_TABLE,
) = _sky_group_tables()


def effective_arm_basis(x_arm, y_arm) -> np.ndarray:
    """Rows ``(e1, e2, normal)``: the effective arms of an interferometer
    with arms ``x_arm``, ``y_arm`` (any opening angle) and its plane normal,
    so that its detector tensor is ``(sin alpha / 2) (e1 e1 - e2 e2)``."""
    x = np.asarray(x_arm, dtype=float)
    y = np.asarray(y_arm, dtype=float)
    x, y = x / np.linalg.norm(x), y / np.linalg.norm(y)
    normal = np.cross(x, y)
    if np.linalg.norm(normal) < 1e-8:
        raise ValueError("the arms are parallel")
    normal /= np.linalg.norm(normal)
    bisector = (x + y) / np.linalg.norm(x + y)
    perp = np.cross(normal, bisector)  # in plane, towards y
    e1 = (bisector - perp) / np.sqrt(2.0)
    e2 = (bisector + perp) / np.sqrt(2.0)
    return np.stack([e1, e2, normal])


def arms_from_geodetic(latitude, longitude, bisector_azimuth, opening_angle):
    """Earth-fixed unit arms of a horizontal interferometer.

    ``bisector_azimuth`` is the angle of the arms' bisector from local East
    towards North (bilby's arm-azimuth convention), ``opening_angle`` the angle
    between the arms (``pi/2`` for an L, ``pi/3`` for one ET channel).
    """
    sl, cl = np.sin(latitude), np.cos(latitude)
    so, co = np.sin(longitude), np.cos(longitude)
    east = np.array([-so, co, 0.0])
    north = np.array([-sl * co, -sl * so, cl])

    def arm(azimuth):
        return np.cos(azimuth) * east + np.sin(azimuth) * north

    half = 0.5 * float(opening_angle)
    return arm(bisector_azimuth - half), arm(bisector_azimuth + half)


class SingleInterferometerGroupAction(TriangularDetectorGroupAction):
    """The ``D4h`` (times polarisation/phase) group of one interferometer.

    A drop-in for :class:`~nessai_gw.group_mixture.TriangularDetectorGroupAction`
    (and so for :class:`~nessai_gw.group_mixture.PrimeSpaceTriangularGroupAction`
    and the proposal factory): the detector frame has rows ``(e1, e2, normal)``
    (:func:`effective_arm_basis`), so the inherited frame maps, sky-frame
    rotation and geocentre delay apply unchanged.

    Parameters
    ----------
    reference_time : float
        Geocentric GPS time of the event (its GMST sets the frame).
    x_arm, y_arm : array_like
        Earth-fixed unit vectors along the arms; their opening angle is
        arbitrary.  See :meth:`from_interferometer` and :meth:`from_geodetic`.
    vertex : array_like
        Earth-fixed detector position (metres).
    phase_reflection, polarisation_quarter, polarisation_offset
        As for :class:`~nessai_gw.group_mixture.TriangularDetectorGroupAction`.
    azimuth_offset : float, optional
        Must be 0: the sky domain's walls are mirror lines of the group, so
        they cannot be moved.
    inclination_reflection : bool, optional
        Add the fixed-sky ``theta_jn -> pi - theta_jn``, ``psi -> 2 beta -
        psi`` element (module docstring); the fundamental domain then also
        has ``cos theta_jn >= 0``.
    """

    #: The sky fundamental domain spans this fraction of ``sky_u`` and its
    #: wall is a mirror line, so :class:`AdaptiveFundamentalDomain` keeps the
    #: sky seam fixed.
    sky_wedge = 0.125
    sky_seam_fixed = True
    sky_group_size = SINGLE_INTERFEROMETER_SKY_GROUP_SIZE

    def __init__(
        self,
        reference_time,
        x_arm,
        y_arm,
        vertex,
        phase_reflection=False,
        azimuth_offset=0.0,
        polarisation_quarter=False,
        polarisation_offset=0.0,
        inclination_reflection=False,
    ):
        if azimuth_offset:
            raise ValueError(
                "the single-interferometer sky domain is bounded by mirror "
                "lines; azimuth_offset must be 0"
            )
        basis = effective_arm_basis(x_arm, y_arm)
        self.x_arm = np.asarray(x_arm, dtype=float)
        self.y_arm = np.asarray(y_arm, dtype=float)
        self.opening_angle = float(
            np.arccos(np.clip(self.x_arm @ self.y_arm / (
                np.linalg.norm(self.x_arm) * np.linalg.norm(self.y_arm)),
                -1.0, 1.0))
        )
        super().__init__(
            reference_time,
            plane_normal=basis[2],
            vertex=vertex,
            phase_reflection=phase_reflection,
            azimuth_offset=0.0,
            polarisation_quarter=polarisation_quarter,
            polarisation_offset=polarisation_offset,
        )
        # replace the triangle's basis (e1 from the Earth's axis) with the
        # effective arms, and the sky frame built from it
        self._basis_np = basis
        self._basis = torch.as_tensor(basis, dtype=torch.float64)
        self.set_gmst(self.gmst)
        n_phase = 4 if self.polarisation_quarter else (
            2 if self.phase_reflection else 1)
        self._n_phase = n_phase
        self.inclination_reflection = bool(inclination_reflection)
        self.group_size = (SINGLE_INTERFEROMETER_SKY_GROUP_SIZE * n_phase
                           * (2 if self.inclination_reflection else 1))
        # detector tensor, up to scale: the effective arms' e1 e1 - e2 e2
        self._D = torch.as_tensor(
            basis.T @ np.diag([1.0, -1.0, 0.0]) @ basis, dtype=torch.float64)
        self._mats = torch.as_tensor(_SKY_MATRICES, dtype=torch.float64)
        self._signs = torch.as_tensor(_SKY_SIGNS, dtype=torch.float64)
        self._improper = torch.as_tensor(_SKY_DETS < 0)
        self._sky_inverse = torch.as_tensor(SKY_INVERSE_TABLE)

    @classmethod
    def from_interferometer(cls, interferometer, reference_time, **kwargs):
        """From a bilby interferometer (its arms and vertex)."""
        geometry = getattr(interferometer, "geometry", interferometer)
        return cls(
            reference_time,
            x_arm=geometry.x,
            y_arm=geometry.y,
            vertex=geometry.vertex,
            **kwargs,
        )

    @classmethod
    def from_geodetic(cls, reference_time, latitude, longitude,
                      bisector_azimuth, opening_angle=0.5 * np.pi,
                      height=0.0, **kwargs):
        """From the site (radians, metres), the arms' bisector azimuth (from
        East towards North) and their opening angle."""
        x_arm, y_arm = arms_from_geodetic(
            latitude, longitude, bisector_azimuth, opening_angle
        )
        return cls(
            reference_time,
            x_arm=x_arm,
            y_arm=y_arm,
            vertex=detector_vertex_from_geodetic(latitude, longitude, height),
            **kwargs,
        )

    # -- modes ---------------------------------------------------------------

    def _split3(self, modes):
        """``(sky, phase_step, tau)`` of the mode index."""
        modes = torch.as_tensor(modes)
        n = SINGLE_INTERFEROMETER_SKY_GROUP_SIZE
        n_phase = getattr(self, "_n_phase", None) or (
            4 if self.polarisation_quarter else (
                2 if self.phase_reflection else 1))
        rest = torch.div(modes, n, rounding_mode="floor")
        return (torch.remainder(modes, n), torch.remainder(rest, n_phase),
                torch.div(rest, n_phase, rounding_mode="floor") == 1)

    def _split(self, modes):
        sky, step, _ = self._split3(modes)
        return sky, step

    def _decode(self, modes: torch.Tensor):
        """``(k, reflected, phase_step)``: the sky quarter-turn count, whether
        the element flips ``cos theta_jn`` (an improper sky element or,
        exclusively, the inclination reflection), and the phase-sector
        element (bool for the ``Z2``, int ``0..3`` for the quarter turn)."""
        sky, step, tau = self._split3(modes)
        k = torch.remainder(sky, 4).to(torch.float64)
        reflected = self._improper.to(sky.device)[sky] ^ tau
        if self.polarisation_quarter:
            return k, reflected, step
        return k, reflected, step == 1

    def _invert_modes(self, modes: torch.Tensor) -> torch.Tensor:
        sky, step, tau = self._split3(modes)
        if self.polarisation_quarter:
            step = torch.remainder(-step, 4)
        n = SINGLE_INTERFEROMETER_SKY_GROUP_SIZE
        return (
            self._sky_inverse.to(sky.device)[sky]
            + n * step + n * self._n_phase * tau.to(step.dtype)
        )

    @property
    def mode_factor_sizes(self):
        """The sky ``D4h`` as one factor, the phase sector as another, the
        inclination reflection as a third."""
        n = SINGLE_INTERFEROMETER_SKY_GROUP_SIZE
        if self.polarisation_quarter:
            sizes = [n, 4]
        elif self.phase_reflection:
            sizes = [n, 2]
        else:
            sizes = [n]
        if getattr(self, "inclination_reflection", False):
            sizes = (sizes if len(sizes) > 1 else sizes + [1]) + [2]
        return sizes

    def _null_cross_angle(self, u, v, w):
        """``beta``, the polarisation angle at which ``F_x`` vanishes (mod
        ``pi/2``), for the direction with polarisation basis ``u, v`` (as
        ``m = -u sin psi - v cos psi``) and propagation axis ``w``:
        ``F_+(psi) = a cos 2 psi + b sin 2 psi`` is extremal there."""
        D = self._D.to(u.dtype)

        def f_plus(m):
            n = torch.linalg.cross(w, m, dim=-1)
            return ((m @ D) * m).sum(-1) - ((n @ D) * n).sum(-1)

        a = f_plus(-v)
        b = f_plus(-(u + v) / np.sqrt(2.0))
        return 0.5 * torch.atan2(b, a)

    # -- action ----------------------------------------------------------------

    def __call__(self, point_dict: dict, modes, inverse: bool = False) -> dict:
        ra = point_dict["ra"]
        dtype = ra.dtype
        dec = torch.asin(torch.clamp(point_dict["sin_dec"], -1.0, 1.0))
        psi = point_dict["psi"]
        phase = point_dict["phase"]
        cos_theta_jn = point_dict["cos_theta_jn"]

        modes = torch.as_tensor(modes, device=ra.device)
        if inverse:
            modes = self._invert_modes(modes)
        sky, phase_step, tau = self._split3(modes)
        if not self.polarisation_quarter:
            phase_step = phase_step == 1

        basis = self._basis.to(dtype)
        u, v, w = _uvw(ra - self.gmst, 0.5 * np.pi - dec)
        m = -u * torch.sin(psi)[..., None] - v * torch.cos(psi)[..., None]
        # Earth-fixed -> frame, act, frame -> Earth-fixed: basis^T O basis
        O = basis.T @ self._mats.to(dtype)[sky] @ basis
        w_t = (O @ w[..., None])[..., 0]
        m_t = (O @ m[..., None])[..., 0]

        dec_t = torch.asin(torch.clamp(w_t[..., 2], -1.0, 1.0))
        ra_t = torch.remainder(
            torch.atan2(w_t[..., 1], w_t[..., 0]) + self.gmst, _TWO_PI
        )
        u_t, v_t, _ = _uvw(ra_t - self.gmst, 0.5 * np.pi - dec_t)
        psi_t = _polarisation_angle(m_t, u_t, v_t)
        # a -D element: psi + pi/2 flips both polarisations back
        psi_t = psi_t + torch.where(
            self._signs.to(dtype)[sky] < 0, 0.5 * np.pi, 0.0
        )
        improper = self._improper.to(sky.device)[sky]
        if getattr(self, "inclination_reflection", False):
            # fixed sky, F_x -> -F_x: psi reflected about F_x's zero
            beta = self._null_cross_angle(u_t, v_t, w_t)
            psi_t = torch.where(tau, 2.0 * beta - psi_t, psi_t)
            improper = improper ^ tau
        cos_theta_jn = torch.where(improper, -cos_theta_jn, cos_theta_jn)

        if self.polarisation_quarter:
            shift = 0.5 * np.pi * phase_step.to(dtype)
            psi_t = psi_t + shift
            phase_t = torch.remainder(phase - shift, _TWO_PI)
        else:
            phase_t = torch.where(
                phase_step, torch.remainder(phase + np.pi, _TWO_PI), phase
            )
        out = {
            "ra": ra_t,
            "sin_dec": torch.sin(dec_t),
            "cos_theta_jn": cos_theta_jn,
            "psi": torch.remainder(psi_t, np.pi),
            "phase": phase_t,
        }
        if "phi_jl" in point_dict:
            # precessing spins: an improper element flips N in the binary's
            # frame, i.e. theta_jn -> pi - theta_jn with phi_jl -> phi_jl + pi
            # (as the triangle's plane reflection)
            out["phi_jl"] = torch.where(
                improper,
                torch.remainder(point_dict["phi_jl"] + np.pi, _TWO_PI),
                point_dict["phi_jl"],
            )
        for key in TIME_PARAMETERS:
            if key in point_dict:
                out[key] = (
                    point_dict[key]
                    + self._geocenter_delay(ra, dec)
                    - self._geocenter_delay(ra_t, dec_t)
                )
        return out

    def in_fundamental_domain(self, point_dict: dict) -> torch.Tensor:
        """The canonical image: frame azimuth in ``[0, pi/4)`` (between the
        effective arm ``e1`` and the diagonal, both mirror lines) above the
        plane, plus the phase-sector clauses of the triangle."""
        dec = torch.asin(torch.clamp(point_dict["sin_dec"], -1.0, 1.0))
        lam_f, beta_f, _ = self._to_frame(
            point_dict["ra"], dec, point_dict["psi"]
        )
        mask = (torch.remainder(lam_f, _TWO_PI) < 0.25 * np.pi) & (
            beta_f >= 0.0)
        if getattr(self, "inclination_reflection", False):
            mask = mask & (point_dict["cos_theta_jn"] >= 0.0)
        if self.phase_reflection:
            mask = mask & (
                torch.remainder(point_dict["phase"], _TWO_PI) < np.pi
            )
        if self.polarisation_quarter:
            mask = mask & (
                torch.remainder(
                    point_dict["psi"] - self.polarisation_offset, np.pi
                ) < 0.5 * np.pi
            )
        return mask


def make_single_interferometer_group_flow_proposal(
    sampling_parameters,
    reference_time,
    x_arm,
    y_arm,
    vertex,
    phase_reflection=False,
    polarisation_quarter=True,
    polarisation_offset=0.0,
    inclination_reflection=False,
    **kwargs,
):
    """:func:`~nessai_gw.group_mixture.make_triangular_group_flow_proposal`
    with the :class:`SingleInterferometerGroupAction` of one interferometer
    (arms ``x_arm``, ``y_arm`` at any opening angle, at ``vertex``).  The other
    keyword arguments are passed through; pair it with
    :func:`~nessai_gw.group_mixture.triangular_group_reparameterisations`
    built with this ``vertex``."""
    from .group_mixture import make_triangular_group_flow_proposal

    action = SingleInterferometerGroupAction(
        reference_time,
        x_arm=x_arm,
        y_arm=y_arm,
        vertex=vertex,
        phase_reflection=phase_reflection,
        polarisation_quarter=polarisation_quarter,
        polarisation_offset=polarisation_offset,
        inclination_reflection=inclination_reflection,
    )
    return make_triangular_group_flow_proposal(
        sampling_parameters,
        reference_time,
        plane_normal=action.plane_normal,
        vertex=vertex,
        phase_reflection=phase_reflection,
        polarisation_quarter=polarisation_quarter,
        polarisation_offset=polarisation_offset,
        base_action=action,
        **kwargs,
    )
